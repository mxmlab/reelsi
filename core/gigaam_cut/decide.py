DECIDE_MARKUP_SCHEMA = {
    "type": "object",
    "properties": {
        "text": {"type": "string"},
        "notes": {"type": "string"},
        "duplicate_groups": {
            "type": "array",
            "items": {
                "type": "object",
                "properties": {
                    "takes": {"type": "integer", "minimum": 2},
                    "kept": {"type": "integer", "minimum": 1},
                    "reason": {"type": "string"},
                },
                "required": ["takes", "kept", "reason"],
                "additionalProperties": False,
            },
        },
    },
    "required": ["text", "notes", "duplicate_groups"],
    "additionalProperties": False,
}


def parse_markup(text):
    """Размеченный моделью текст -> [(токен, выкинуть?)]. Скобки [ ] могут быть
    не закрыты (модель оборвалась) — тогда всё до конца считается вырезанным."""
    out, depth = [], 0
    for chunk in re.findall(r"[\[\]]|[а-яёa-zA-Z0-9]+", text or "", re.I):
        if chunk == "[":
            depth += 1
        elif chunk == "]":
            depth = max(0, depth - 1)
        else:
            out.append((_tok(chunk) or chunk.lower(), depth > 0))
    return out
# Минимальная доля слов ролика, найденных в ответе модели (0..1).
# Если совпало меньше — модель вернула отказ, пустышку или текст из другого ролика;
# пустой drop при этом маскирует сбой под «резать нечего».
MIN_COVER = 0.5


def align_markup(words, marked, emit=console_emit):
    """Наложить разметку модели на НАШИ слова (у нас тайминги, у неё — решение).

    Модель обязана вернуть текст дословно, но может подправить окончание,
    пропустить слово или, наоборот, что-то вставить. Поэтому выравниваем
    difflib-ом: где токены совпали — переносим флаг «выкинуть»; где модель
    напутала — слово ОСТАЁТСЯ (лучше оставить лишнее, чем молча вырезать то,
    чего модель не показывала). Возвращает (drop:set, покрытие 0..1)."""
    emit = wrap_emit(emit)
    ours = [_tok(w["w"]) for w in words]
    theirs = [t for t, _ in marked]
    flags = [f for _, f in marked]
    drop, matched = set(), 0
    sm = difflib.SequenceMatcher(None, ours, theirs, autojunk=False)
    for tag, i1, i2, j1, j2 in sm.get_opcodes():
        if tag != "equal":
            continue
        matched += i2 - i1
        for k in range(i2 - i1):
            if flags[j1 + k]:
                drop.add(i1 + k)
    cover = matched / max(1, len(ours))
    if cover < 0.95:
        emit("  разметка: совпало {pct:.0f}% слов — остальные оставлены как есть",
             pct=100 * cover, flush=True)
    return drop, cover


def decide_markup(words, full_text, model=None, emit=console_emit, silence_bounds=None):

    """Модель возвращает ВЕСЬ текст ролика, заключив в [ ] то, что надо выкинуть.
    Никакой арифметики и никакого поиска цитат: позиция куска задана самим
    текстом, а тайминги мы берём из своих слов. Смысловые решения целиком на
    модели — код только выравнивает её ответ на наш пословный поток."""
    emit = wrap_emit(emit)
    user = ("ПОЛНАЯ расшифровка ролика:\n" + " ".join(w["w"] for w in words) +
            "\n\nВерни этот же текст целиком, заключив в [ ] всё, что выкинуть.")
    # бюджет: сам текст (~12 токенов на слово) + место на размышления
    lvl = _decide_reasoning()
    data = aicut._ask_json(_sys(DECIDE_MARKUP_SYS), user, DECIDE_MARKUP_SCHEMA, model=model,
                           max_tokens=aicut.reason_budget(max(2000, len(words) * 12), lvl),
                           emit=emit, temperature=0.2, reasoning=lvl,
                           profile=aicut.step_profile("cut"), step="cut-markup")
    # Metadata нужна только для диагностики: источником резов остаётся text.
    groups = []
    raw_groups = data.get("duplicate_groups", []) if isinstance(data, dict) else []
    if not isinstance(raw_groups, list):
        raw_groups = []
    for item in raw_groups:
        if not isinstance(item, dict):
            continue
        takes, kept_take, reason = item.get("takes"), item.get("kept"), item.get("reason")
        if (type(takes) is not int or takes < 2 or type(kept_take) is not int or
                kept_take < 1 or kept_take > takes or not isinstance(reason, str)):
            continue
        groups.append((takes, kept_take, " ".join(reason.split())[:120]))
    summary = "; ".join(f"{takes}→{kept_take}/{reason}" for takes, kept_take, reason in groups)
    emit(f"duplicate_groups: {len(groups)}{f' ({summary})' if summary else ''}", flush=True)
    marked = parse_markup(data.get("text", "") if isinstance(data, dict) else "")
    drop, cover = align_markup(words, marked, emit=emit)
    if cover < MIN_COVER:
        raise SystemExit(
            f"ответ модели не про этот ролик (совпало {100 * cover:.0f}%) — "
            f"ничего не перезаписываю — прошлая нарезка цела. "
            f"Проверь модель и промпт в настройках ⚙ и запусти ещё раз.")
    kept = set(i for i in range(len(words)) if i not in drop)
    cutlog = [{"t0": round(words[a]["start"], 2), "t1": round(words[b]["end"], 2),
               "text": _words_text(words, a, b),
               "reason": "слова (GigaAM + 27b, разметка)", "source": "27b (разметка)"}
              for a, b in _ranges(sorted(drop))]
    emit("GigaAM+27b (разметка): выкинуто слов {drop} из {total} "
         "({ranges} диапазонов, совпало {pct:.0f}%). notes: {notes}",
         drop=len(drop), total=len(words), ranges=len(_ranges(sorted(drop))),
         pct=100 * cover, notes=data.get('notes', '') if isinstance(data, dict) else '', flush=True)
    return kept, drop, data.get("notes", "") if isinstance(data, dict) else "", cutlog
