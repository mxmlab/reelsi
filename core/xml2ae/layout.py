def _hl_phrases(items: Sequence[tuple[int, float, float]], fps: float) -> list[tuple[float, float]]:
    """Фразы хайлайта из слов [(индекс, начало, конец)] в кадрах.

    Фраза — подряд идущие выделенные слова: следующее слово начинает новую фразу, если
    его индекс не соседний (разрыв > 1) или пауза между концом предыдущего слова и его
    началом больше TAKE_PHRASE_GAP_S. Возвращаются пары (t_start, t_end) в кадрах:
    начало первого слова фразы и КОНЕЦ последнего — по ним считается удержание.
    `fps` — частота кадров: порог паузы задан в секундах.
    """
    return [ph for ph, _members in _hl_phrase_groups(items, fps)]


def _hl_phrase_groups(items: Sequence[tuple[int, float, float]], fps: float
                      ) -> list[tuple[tuple[float, float], list[int]]]:
    """То же, что `_hl_phrases`, но с составом фразы: [(фраза, [индексы слов]), ...].

    Состав нужен правилу «наезд только на сильные жёлтые» (см. `_yellow_strong_phrases`):
    сила фразы — максимум её слов, а пара (t_start, t_end) о концах говорит только
    косвенно. Группировка РОВНО та же, второй копии правила нет.
    """
    gap = round(TAKE_PHRASE_GAP_S * float(fps))
    out: list[tuple[tuple[float, float], list[int]]] = []
    prev_i: int | None = None
    prev_e = 0.0
    for _i, _s, _e in sorted(items, key=lambda x: x[0]):
        if (out and prev_i is not None and _i - prev_i <= 1
                and (float(_s) - prev_e) <= gap):
            ph, members = out[-1]
            out[-1] = ((ph[0], max(ph[1], float(_e))), members + [int(_i)])
        else:
            out.append(((float(_s), float(_e)), [int(_i)]))
        prev_i, prev_e = _i, float(_e)
    out.sort(key=lambda x: x[0])
    return out


