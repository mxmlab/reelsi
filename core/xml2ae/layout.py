def _stack_layout(subs: Sequence[tuple[float, float, str]], hl: set[int] | Sequence[int], breaks: Any = None, joins: Any = None) -> tuple[list[int], list[float]]:
    """For highlighted words that are ADJACENT in reading order, assign a stack row
    (0,1,2,...) and a shared group-end frame (whole stack disappears together).
    `breaks` = set of word indices AFTER which the stack restarts (ручной разделитель
    «палочка» между жёлтыми — начать стопку заново).
    `joins` = set of word indices AFTER which the word is joined with next word
    in the same row (склейка в строку). Returns rows[], gend[]."""
    breaks = breaks or set()
    joins = (joins or set()) - breaks
    n = len(subs)
    rows = [0] * n
    gend = [e for (s, e, w) in subs]
    i = 0
    while i < n:
        if i in hl:
            j = i
            while j + 1 < n and (j + 1) in hl and j not in breaks:
                j += 1
            run_end = max(subs[k][1] for k in range(i, j + 1))
            cur_r = 0
            for k in range(i, j + 1):
                rows[k] = cur_r
                gend[k] = run_end
                if k not in joins:
                    cur_r += 1
            i = j + 1
        else:
            i += 1
    return rows, gend


def _censor_windows(subs: Sequence[tuple[float, float, str]], fps: float) -> list[tuple[float, float]]:
    """Audio-mute windows (sec) for the middle letter of each censored subtitle word.
    A word is censored if it carries a '*' (from censor.py or manual edit)."""
    wins = []
    for s, e, w in subs:
        n = len(w or "")
        if not n or "*" not in (w or ""):
            continue
        m = w.index("*")
        dur = e - s
        if dur <= 0:
            continue
        wins.append(((s + dur * m / n) / fps, (s + dur * (m + 1) / n) / fps))
    return wins


def _cam_overlaps(clips: Sequence[Sequence[Any]], sf: float, ef: float, fps: float, ci: int) -> list[dict[str, Any]]:
    """Все клипы камеры `ci`, пересекающиеся с окном [sf,ef] (кадры). Для каждого — участок
    ИСХОДНИКА, реально показанный там (учёт source in-point), и место на таймлайне.
    -> [dict(ci, tl_start, tl_end, src_start, src_end, scale)] (сек). Скрытые клипы cam2+ (не
    показываемые перебивки) пропускаются."""
    out = []
    for cl in clips:
        cs, ce, cin, en, sc = cl[0], cl[1], cl[2], cl[4], cl[5]
        if ci > 0 and not en:                      # скрытый клип 2-й+ камеры — не в кадре
            continue
        a = max(sf, cs); b = min(ef, ce)
        if b <= a:
            continue
        out.append(dict(ci=ci, tl_start=a / fps, tl_end=b / fps, scale=sc,
                        src_start=(cin + (a - cs)) / fps, src_end=(cin + (b - cs)) / fps))
    return out


def cover_sweep(raw: Sequence[Sequence[Any]]) -> list[tuple[Any, Any, int]]:
    """Кто виден на каждом элементарном отрезке таймлайна: [(b0, b1, k), ...], где k —
    ИНДЕКС победившего клипа в raw. Побеждает верхняя дорожка (максимальный ci), при
    равном ci — тот, что раньше в raw (то есть раньше в XML).

    raw — [(start, end, ci, ...), ...]; поля после ci игнорируются, их разбирает
    вызывающий. Единица времени любая (кадры или секунды), лишь бы одна на весь список.

    Было O(R²): на каждую из ~2R границ пересматривался ВЕСЬ список клипов. На вертикалке
    в пару сотен клипов это незаметно, но час лекции с тысячами клипов давал секунды на
    КАЖДЫЙ вызов — а зовут это и раскладка, и предпросмотр, и черновик. Заметающая прямая
    даёт тот же ответ за O(R log R): границы — это все концы клипов, поэтому «клип
    покрывает [b0, b1]» (s <= b0 и e >= b1) равносильно «s <= b0 < e», а это обычный
    интервал активности.
    """
    if not raw:
        return []
    order = sorted(range(len(raw)), key=lambda k: raw[k][0])   # клипы по началу — для входа
    bounds = sorted({t for cl in raw for t in (cl[0], cl[1])})
    exp: list[tuple[Any, int]] = []             # куча (конец, индекс): когда клип перестаёт быть активным
    live: dict[Any, set[int]] = {}              # ci -> множество индексов активных клипов этой камеры
    out, p = [], 0
    for b0, b1 in zip(bounds, bounds[1:]):
        while p < len(order) and raw[order[p]][0] <= b0:       # вошли в кадр
            k = order[p]
            p += 1
            heapq.heappush(exp, (raw[k][1], k))
            live.setdefault(raw[k][2], set()).add(k)
        while exp and exp[0][0] <= b0:                         # вышли (конец не включаем)
            _e, k = heapq.heappop(exp)
            live[raw[k][2]].discard(k)
        top = max((ci for ci, ks in live.items() if ks), default=None)
        if top is None:                                        # дырка в таймлайне
            continue
        out.append((b0, b1, min(live[top])))
    return out


def _show_segments(cams: Sequence[dict[str, Any]]) -> list[tuple[float, float, int]]:
    """Склеенные сегменты ПОКАЗА (какая камера реально видна): [(start, end, ci), ...].
    Верхняя включённая дорожка побеждает; смежные куски одной камеры склеены (VAD-стыки
    внутри камеры — НЕ смена кадра)."""
    raw = []
    for ci, c in enumerate(cams):
        for cl in c["clips"]:
            if cl[4] and cl[1] > cl[0]:            # только включённые (реально видимые) клипы
                raw.append((cl[0], cl[1], ci))
    segs: list[tuple[float, float, int]] = []      # склеенные сегменты показа: (start, end, ci)
    for b0, b1, k in cover_sweep(raw):
        ci = raw[k][2]
        if segs and segs[-1][2] == ci and abs(segs[-1][1] - b0) < 1e-6:
            segs[-1] = (segs[-1][0], b1, ci)        # та же камера подряд — склеиваем
        else:
            segs.append((b0, b1, ci))
    return segs


def _cam_change_frames(cams: Sequence[dict[str, Any]]) -> list[float]:
    """Кадры, где меняется ПОКАЗЫВАЕМАЯ камера (срезы кадра). -> [frame, ...] по возрастанию."""
    segs = _show_segments(cams)
    return [segs[k][0] for k in range(1, len(segs)) if segs[k][2] != segs[k - 1][2]]


def _zoom_cut_frames(cams: Sequence[dict[str, Any]], fps: float = 60.0, min_gap_sec: float = 2.0) -> list[float]:
    """Кадры срезов для зум-стилей: смены показываемой камеры ПЛЮС собственные склейки кам1
    (границы её клипов) там, где смен камеры нет. Однокамерный проект раньше уходил в случайные
    интервалы 4–7 c — кейфреймы вставали посреди кадра, а не на срезах. Слишком частые срезы
    прореживаем: между соседними ключами держим min_gap_sec, иначе зуму негде дрейфовать.
    -> [frame, ...] по возрастанию, без 0 (его добавляет вызывающий)."""
    fps = float(fps) or 60.0
    changes = set(_cam_change_frames(cams))          # смены камеры — берём ВСЕ, даже короткие перебивки
    glue = {cl[0] for cl in cams[0]["clips"]         # собственные склейки кам1 = тоже срезы кадра
            if cl[4] and cl[0] > 0} - changes
    last: float | int
    gap, out, last = max(1.0, float(min_gap_sec)) * fps, [], 0
    for f in sorted(changes | glue):
        if f in changes or f - last >= gap:          # склейки кам1 прореживаем: зуму нужно где дрейфовать
            out.append(f); last = f
    return out


def _cam1_return_frames(cams: Sequence[dict[str, Any]]) -> list[float]:
    """Кадры, где показ ВОЗВРАЩАЕТСЯ на Камеру 1 (срез перебивка→кам1). Именно тут ставится
    импульс pulse-зума. Раньше брались концы ВСЕХ клипов cam2+ — при ручной раскладке смежные
    куски одной перебивки давали кейфрейм ПОСРЕДИ показа камеры, не на срезе."""
    segs = _show_segments(cams)
    return [segs[k][0] for k in range(1, len(segs)) if segs[k][2] == 0 and segs[k - 1][2] != 0]


def _camera_cut_segments(cams: Sequence[dict[str, Any]], cam: int, fps: float = 60.0,
                         min_gap_sec: float = 2.0) -> tuple[list[float], list[float]]:
    """(frames, seg_ends) для камеры `cam` (0=cam1, 1=cam2...).
    Для cam=0 — ровно прежняя раскладка: кадр 0 + срезы смен камеры + склейки кам1,
    конец — следующий срез или конец ролика.
    Для cam>0 — реальные интервалы показа этой камеры (сегменты с ci == cam):
    frames = начала интервалов (срезы входа на эту камеру + возможные склейки внутри неё),
    seg_ends = концы интервалов (срез ухода с этой камеры / следующая склейка).
    Пустой список — если камеры нет на таймлайне.
    """
    fps = float(fps) or 60.0
    if cam == 0:
        frames = sorted(set([0] + _zoom_cut_frames(cams, fps=fps)))
        dur = max((cl[1] for c in cams for cl in c["clips"] if cl[4]), default=frames[-1] + fps)
        seg_ends = frames[1:] + [max(dur, frames[-1] + 1)]
        return frames, seg_ends

    if cam >= len(cams):
        return [], []
    segs = _show_segments(cams)
    cam_segs = [(s[0], s[1]) for s in segs if s[2] == cam and s[1] > s[0]]
    if not cam_segs:
        return [], []

    glue = sorted(cl[0] for cl in cams[cam]["clips"] if cl[4] and cl[0] > 0)
    gap = max(1.0, float(min_gap_sec)) * fps
    frames_out: list[float] = []
    seg_ends_out: list[float] = []
    for s0, s1 in cam_segs:
        cuts = [s0]
        last = s0
        for g in glue:
            if s0 < g < s1 and (g - last >= gap) and (s1 - g >= gap):
                cuts.append(g)
                last = g
        for idx_c in range(len(cuts)):
            frames_out.append(cuts[idx_c])
            seg_ends_out.append(cuts[idx_c + 1] if idx_c + 1 < len(cuts) else s1)
    return frames_out, seg_ends_out


def _cam1_drift_keys(cams: Sequence[dict[str, Any]], lo: float = 100.0, hi: float = 160.0, min_diff: float = 10.0, fps: float = 60.0,
                     big: float | None = None, punch: int | None = None, start: bool = True,
                     cam: int = 0, take: dict[str, Any] | None = None) -> list[Any]:
    """Дрейф-зум (cam=0 для Камеры 1, cam=1 для Камеры 2). ВСЕ ключи — ease (безье), никаких HOLD:
    «скачок» на кате получается из двух соседних ключей (цель дрейфа за 1 кадр до среза + новое
    значение в срезе). Старт — как у pulse: big (182) в первом срезе с фирменным ease-откатом к 100
    за punch кадров, дальше между катами постоянный лёгкий дрейф к случайной цели (если start=False —
    старт со 100%, без наезда).
    -> [(frame, percent, mode), ...], mode: 1 = стартовый ключ big (out = ease как у pulse) ·
    2 = приход отката в 100 (in = ease как у pulse) · 0 = обычный Easy Ease.
    При переданном `take` добавляются наезды в длинных тейках.
    Кадры ключей — реальные срезы показа соответствующей камеры, см. _camera_cut_segments.
    Детерминировано (seed от кадров реза)."""
    import random as _rnd
    fps = int(round(float(fps) or 60))
    big = float(big if big is not None else ZOOM_BIG)
    punch = int(punch if punch is not None else ZOOM_PUNCH)
    frames, seg_ends = _camera_cut_segments(cams, cam=cam, fps=fps)
    if not frames:
        return []
    seed = ("d," if cam == 0 else f"d{cam + 1},") + ",".join(str(f) for f in frames)
    tseed = ("t," if cam == 0 else f"t{cam + 1},") + ",".join(str(f) for f in frames)
    rng = _rnd.Random(seed)
    trng = _rnd.Random(tseed) if take else None
    keys: list[Any]
    prev: list[Any]
    keys, prev = [], [None]

    def _pick() -> float:
        for _ in range(8):
            x = round(rng.uniform(lo, hi), 1)
            if prev[0] is None or abs(x - prev[0]) >= min_diff:
                break
        prev[0] = x
        return x

    if take is None:
        for i, f in enumerate(frames):
            seg_end = int(round(seg_ends[i]))
            tgt = max(f + 1, seg_end - 1)                            # за 1 кадр до следующей смены
            if i == 0:                                               # старт: big -> фирменный ease-откат к 100 -> дрейф
                if not start:
                    keys.append((f, 100.0, 0))
                    prev[0] = 100.0
                    if tgt > f:
                        keys.append((tgt, _pick(), 0))
                    continue
                pe = min(f + punch, max(f + 1, tgt - 2))             # откат сжимается, если срез раньше punch
                keys.append((f, big, 1))                             # out = ease как у pulse (35)
                keys.append((pe, 100.0, 2))                          # in = ease как у pulse (90)
                prev[0] = 100.0
                if tgt > pe + 1:
                    keys.append((tgt, _pick(), 0))                   # дрейф 100 -> w до кадра перед срезом
                continue
            v = _pick()
            keys.append((f, v, 0))                                   # новое значение в срезе: 1 кадр от цели = «скачок»
            if tgt > f:
                keys.append((tgt, _pick(), 0))                       # цель дрейфа перед следующим срезом
        return keys

    # take is not None:
    for i, f in enumerate(frames):
        seg_end = int(round(seg_ends[i]))
        tgt = max(f + 1, seg_end - 1)
        if i == 0:
            if not start:
                keys.append((f, 100.0, 0, 0))
                prev[0] = 100.0
                pe_frame = None
                v = 100.0
            else:
                pe_frame = min(f + punch, max(f + 1, tgt - 2))
                keys.append((f, big, 1, 0))
                keys.append((pe_frame, 100.0, 2, 0))
                prev[0] = 100.0
                v = 100.0
        else:
            v = _pick()
            keys.append((f, v, 0, 0))
            pe_frame = None

        lead_min_frame = int(round(pe_frame + 1)) if pe_frame is not None else int(round(f))
        t_keys = _take_zoom_segment_keys(int(round(f)), seg_end, v, float(fps), take, trng, lead_min_frame)
        if t_keys:
            keys.extend(t_keys)
            last_d = int(round(t_keys[-1][0]))
            if tgt > last_d:
                keys.append((tgt, _pick(), 0, 0))
        else:
            after_ref = pe_frame if pe_frame is not None else f
            if tgt > after_ref + 1:
                keys.append((tgt, _pick(), 0, 0))
    return keys


def _merge_same_frame_keys(keys: Sequence[Sequence[Any]] | None,
                           tol: float = 0.5) -> list[Any]:
    """Склейка ключей на ОДНОМ кадре (|Δ| < tol кадра) в ОДИН — для списка ключей
    зума любой камеры и любого режима.

    Зачем. На склейке сходятся два независимых источника ключей: скачок/дрейф
    (`_cam1_jump_keys`/`_cam1_drift_keys`/`_cam1_zoom_keys` — ключ на самом кадре
    среза) и наезд хайлайта/тейка (`_take_zoom_segment_keys` — подъезд `a`, который
    при `a == cur_ref` встаёт на тот же кадр). AE `setValueAtTime` на занятый
    момент НЕ добавляет ключ, а ПЕРЕПИСЫВАЕТ его: ключей в AE меньше, чем в
    массиве, и `CAM*_HOLDS`/`CAM*_EASE` по индексам (`holds[k-1]`, `ease[z2]`,
    цикл `k` от 1 до `numKeys`) съезжают на один — наезд становится HOLD,
    удержание плавным, и слежение за головой, посчитанное под план, уводит край
    кадра (C1603: масштаб держится 103.9 до 2917 и прыгает в 133.2).
    Склейка в Python оставляет в массиве ровно те ключи, что будут в AE.

    Остаётся ОДИН ключ: ЗНАЧЕНИЕ, РЕЖИМ для `_zoom_key_eases` и 4-е поле (`hold` —
    ВЫХОД ключа, отрезок от него до следующего) берутся от последнего: он и
    перезаписывает ключ в AE. ВХОД (интерполяция отрезка, приходящего в этот кадр)
    лежит в 4-м поле ПРЕДЫДУЩЕГО ключа и склейкой не трогается — как не трогал его
    и прежний список. Число элементов ключа сохраняется как у последнего:
    4-элементные (jump, take) не превращаются в 3-элементные и наоборот — иначе
    поехал бы .jsx. Тип ключа (tuple/list) тоже сохраняется: ключи генераторов —
    кортежи, и сторож `test_plan_camera_split` сверяет хвост ключа как `got[2:] ==
    ref[2:]`.
    """
    out: list[Any] = []
    for k in keys or []:
        if out and abs(float(k[0]) - float(out[-1][0])) < tol:
            first = out[-1]
            n = max(len(first), len(k))          # форму ключа держим как у последнего
            merged: list[Any] = [float(k[0]), k[1]]
            if n > 2:
                merged.append(int(k[2]) if len(k) > 2 else int(first[2]))
            if n > 3:
                merged.append(bool(k[3]) if len(k) > 3 else bool(first[3]))
            out[-1] = tuple(merged) if isinstance(k, tuple) else merged
            continue
        out.append(list(k) if isinstance(k, list) else k)
    return out


def _zoom_key_eases(keys: Sequence[Sequence[Any]]) -> list[list[float]]:
    """[[in, out], ...] — влияние ЭТАЛОННОЙ кривой на КАЖДЫЙ ключ зума (для JS-цикла).

    Эталон один на всю сборку: cubic-bezier(0.35,0.01,0.10,0.99) — out 35 у источника
    движения, in 90 у его цели (HL_EASE_OUT/HL_EASE_IN, одно место с этими числами).
    Решение владельца 01.10.2026: так играют ВСЕ движения зума, включая отъезд наезда
    в тейке (был S-образный 75/75 своим числом TAKE_OUT_EASE — числа больше нет) и
    подъёмы pulse/jump, которые раньше оставались на Easy Ease 33.3333.
    Решение владельца 02.10.2026: дрейф зума (режим drift) — тоже на эталонной кривой
    35/90 (out 35 / in 90).

    Исключения:
    * одиночный ключ — движения нет, значения не играют (остаётся EASE_DEFAULT).
    HOLD-ключи (скачок зума) и слежение за головой кривой здесь не задаются вовсе:
    у первых работает тип интерполяции (CAM1_HOLDS), у вторых — EASE_DEFAULT
    (plan_camera.py). Длина списка совпадает с CAM1_SCALE."""
    out: list[list[float]] = []
    for _ in keys:
        out.append([EASE_DEFAULT, EASE_DEFAULT] if len(keys) < 2
                   else [cast(float, HL_EASE_IN), cast(float, HL_EASE_OUT)])
    return out


def _ae_ease_pair(influence_in: float, influence_out: float) -> tuple[float, float, float]:
    """Кривая значений между двумя ключами AE: влияния in/out -> параметры кривой.

    Скорость у ключей зума/слежения всегда 0, поэтому перевод влияний в кривую
    точный (та же формула, что `aeEase` в `static/app/85-inserts-view.js`):
    x = cubic-bezier(out/100, 0, 1-in/100, 1). Возвращает (p1x, p2x, p3-явно-1).
    """
    return (float(influence_out) / 100.0, 1.0 - float(influence_in) / 100.0, 1.0)


def _bezier_curve_y(p1x: float, p2x: float, u: float) -> float:
    """Y кривой значений в доле отрезка u ∈ [0,1] (x — доля времени).

    Параметр кривой при заданном x ищется Ньютоном (8 шагов) — ровно как
    `bezierT` в предпросмотре: превью и сборка обязаны идти одной кривой.
    """
    q = u
    for _ in range(8):
        om = 1.0 - q
        xt = 3.0 * om * om * q * p1x + 3.0 * om * q * q * p2x + q * q * q
        dx = 3.0 * om * om * p1x + 6.0 * om * q * (p2x - p1x) + 3.0 * q * q * (1.0 - p2x)
        if abs(xt - u) < 1e-6 or dx < 1e-6:
            break
        q -= (xt - u) / dx
        if q < 0.0:
            q = 0.0
        elif q > 1.0:
            q = 1.0
    om = 1.0 - q
    return 3.0 * om * q * q + q * q * q


def _zoom_scale_at(
    keys: Sequence[Sequence[Any]] | None,
    f: float,
    ease: Sequence[Sequence[float]] | None = None,
    holds: Sequence[bool] | None = None,
    fit: float = 100.0,
) -> float:
    """Масштаб нула камеры (множитель, 1.0 = заполнение) на кадре f по кривой AE.

    AE ведёт масштаб по кривой с влиянием ease (скорость 0), а не по прямой: на
    подъезде (in 90 — медленный старт) настоящий масштаб МЕНЬШЕ линейного. Зажим
    слежения, считая масштаб линейным, разрешал сдвиг под больший масштаб — и край
    слоя входил в кадр (жалоба 01.10.2026: полоса слева на наезде камеры 2).
    `fit` — множитель заполнения кадра, как у ключей плана (plan_camera).

    `ease` — влияния [[in, out], ...] по ключу, по умолчанию `_zoom_key_eases(keys)`;
    `holds[i]` — HOLD отрезка от ключа i (значение держится до следующего ключа).
    """
    raw = [(float(k[0]), float(k[1])) for k in (keys or []) if len(k) >= 2]
    if not raw:
        return 1.0
    if ease is None:
        ease = _zoom_key_eases(keys or [])
    if f <= raw[0][0]:
        return raw[0][1] / 100.0 * (fit / 100.0)
    if f >= raw[-1][0]:
        return raw[-1][1] / 100.0 * (fit / 100.0)
    for i in range(len(raw) - 1):
        f0, v0 = raw[i]
        f1, v1 = raw[i + 1]
        if not (f0 <= f < f1):
            continue
        is_hold = bool(holds[i]) if holds and i < len(holds) else False
        span = f1 - f0
        if is_hold or span <= 0.0:
            return v0 / 100.0 * (fit / 100.0)
        # Влияния берутся у СВОИХ ключей конца отрезка: out у уходящего, in у приходящего.
        e_out = ease[i][1] if ease and i < len(ease) and len(ease[i]) > 1 else HL_EASE_OUT
        e_in = ease[i + 1][0] if ease and i + 1 < len(ease) and len(ease[i + 1]) > 0 else HL_EASE_IN
        p1x, p2x, _ = _ae_ease_pair(e_in, e_out)
        q = _bezier_curve_y(p1x, p2x, (f - f0) / span)
        return (v0 + (v1 - v0) * q) / 100.0 * (fit / 100.0)
    return raw[-1][1] / 100.0 * (fit / 100.0)


def _zoom_min_scale(
    keys: Sequence[Sequence[Any]] | None,
    f0: float,
    f1: float,
    ease: Sequence[Sequence[float]] | None = None,
    holds: Sequence[bool] | None = None,
    fit: float = 100.0,
) -> float:
    """Наименьший масштаб нула камеры на отрезке кадров [f0, f1] по кривой AE.

    Зажим слежения обязан считаться по ХУДШЕМУ (наименьшему) масштабу до
    следующего отсчёта: между отсчётами слоя не хватает, и сдвиг, разрешённый по
    масштабу текущего кадра, выводит край слоя в кадр. Наименьшее значение кривой
    лежит на концах отрезка или на ключе внутри него: между ключами кривая
    монотонна, а сами ключи задают её концы.
    """
    if f1 < f0:
        f0, f1 = f1, f0
    pts = [f0, f1]
    for k in (keys or []):
        if len(k) >= 2 and f0 < float(k[0]) < f1:
            pts.append(float(k[0]))
    return min(_zoom_scale_at(keys, f, ease=ease, holds=holds, fit=fit) for f in pts)


def _zoom_key_holds(keys: Sequence[Sequence[Any]] | None, legacy_hold: bool = False) -> list[bool]:
    """[bool, ...] — тип интерполяции отрезка от КАЖДОГО ключа до следующего.
    True = HOLD (значение держится до следующего ключа); False = BEZIER (плавно).
    Для 4-элементных ключей (f, pct, mode, hold) берётся k[3];
    для остальных (ручной cam1_scale, старые данные) — fallback legacy_hold.
    Длина совпадает с len(keys)."""
    return [bool(k[3]) if len(k) >= 4 else bool(legacy_hold) for k in (keys or [])]


def _zoom_max(keys: Sequence[Sequence[Any]] | None, fps: float, ts: float, te: float, holds: Sequence[bool] | bool | None = None, hold: bool | None = None) -> float:
    """Максимум зума Камеры 1 (в %%, как в ключах) на окне [ts, te] сек.

    Группа живёт секунду с лишним, и наезд успевает случиться ВНУТРИ окна — брать зум
    в момент старта нельзя.
    Отрезок i с holds[i]==True вносит в максимум v_i, если [f_i, f_{i+1}) пересекает окно
    (последний ключ — до бесконечности);
    плавный отрезок (holds[i]==False) — линейные значения на концах пересечения с окном.
    До первого ключа — keys[0][1]. Ключей нет — 100.0 (зума нет).
    """
    raw_keys = [(k[0], float(k[1])) for k in (keys or []) if len(k) >= 2]
    if not raw_keys:
        return 100.0
    fps = float(fps) or 60.0
    n = len(raw_keys)
    if holds is None:
        if hold is not None:
            holds = [bool(hold)] * n
        else:
            holds = _zoom_key_holds(keys, legacy_hold=False)
    elif isinstance(holds, bool):
        holds = [holds] * n
    else:
        holds = [bool(h) for h in holds]

    pts = [[f / fps, v] for f, v in raw_keys]

    def _linear_at(t: float) -> float:
        if t <= pts[0][0]:
            return pts[0][1]
        if t >= pts[-1][0]:
            return pts[-1][1]
        for (t0, v0), (t1, v1) in zip(pts, pts[1:]):
            if t0 <= t <= t1:
                return v0 if t1 <= t0 else v0 + (v1 - v0) * (t - t0) / (t1 - t0)
        return pts[-1][1]

    # Быстрый путь: если все HOLD (jump без наездов)
    if all(holds):
        best = 0.0
        for i, (f, v) in enumerate(raw_keys):
            f_end = raw_keys[i + 1][0] if i + 1 < n else float("inf")
            if f / fps <= te + 1e-9 and f_end / fps > ts - 1e-9:
                best = max(best, v)
        if best:
            return best
        return raw_keys[0][1]

    # Быстрый путь: если все плавные (pulse / drift)
    if not any(holds):
        best = max((v for t, v in pts if ts <= t <= te), default=0.0)
        return max(best, _linear_at(ts), _linear_at(te))

    # Смешанный режим
    best = 0.0
    if ts < pts[0][0] + 1e-9:
        best = max(best, pts[0][1])

    for i in range(n):
        t_i = pts[i][0]
        t_next = pts[i + 1][0] if i + 1 < n else float("inf")
        if t_i <= te + 1e-9 and t_next > ts - 1e-9:
            is_hold = holds[i] if i < len(holds) else False
            if is_hold or i == n - 1:
                best = max(best, pts[i][1])
            else:
                t_start_seg = max(ts, t_i)
                t_end_seg = min(te, t_next)
                best = max(best, _linear_at(t_start_seg), _linear_at(t_end_seg))

    if te > pts[-1][0] - 1e-9:
        best = max(best, pts[-1][1])

    return best if best > 0.0 else pts[0][1]


def _span_roto_plan(cams: Sequence[dict[str, Any]], sf: float, ef: float, fps: float) -> list[dict[str, Any]]:
    """Рото по ПОКАЗЫВАЕМОЙ камере в окне [sf,ef] (кадры): перебивки cam2+ там, где включён их
    клип, и Камера 1 во всех разрывах между ними. Так человек перед текстом/видеовставкой и на
    cam1, и на cam2. -> список энтри (без флага intro/vins — его ставит вызывающий)."""
    entries, cover = [], []
    for ci in range(1, len(cams)):                 # включённые клипы вторых камер = перебивки
        for e in _cam_overlaps(cams[ci]["clips"], sf, ef, fps, ci):
            entries.append(e); cover.append((e["tl_start"] * fps, e["tl_end"] * fps))
    cover.sort()
    cur, gaps = sf, []                             # разрывы окна, не покрытые перебивками -> cam1
    for a, b in cover:
        if a > cur:
            gaps.append((cur, a))
        cur = max(cur, b)
    if cur < ef:
        gaps.append((cur, ef))
    for gs, ge in gaps:
        entries += _cam_overlaps(cams[0]["clips"], int(gs), int(ge), fps, 0)
    return entries


HEAD_DEAD_RATIO = 0.03  # мёртвая зона слежения (3% ширины кадра): мелкие покачивания головы игнорируются


def _rdp(pts: list[tuple[float, float]], eps: float = 4.0) -> list[tuple[float, float]]:
    """Рамер–Дуглас–Пекер по (f, y) внутри клипа."""
    if len(pts) <= 2:
        return pts
    x1, y1 = pts[0]
    x2, y2 = pts[-1]
    dx = x2 - x1
    dy = y2 - y1
    denom = (dx * dx + dy * dy) ** 0.5
    max_d = -1.0
    idx = -1
    for i in range(1, len(pts) - 1):
        x0, y0 = pts[i]
        if denom == 0:
            d = ((x0 - x1) ** 2 + (y0 - y1) ** 2) ** 0.5
        else:
            d = abs(dy * x0 - dx * y0 + x2 * y1 - y2 * x1) / denom
        if d > max_d:
            max_d = d
            idx = i
    if max_d > eps:
        left = _rdp(pts[:idx + 1], eps)
        right = _rdp(pts[idx:], eps)
        return left[:-1] + right
    return [pts[0], pts[-1]]


def _cam1_follow_keys(
    cams: Sequence[dict[str, Any]],
    pts: Sequence[Any],
    w_src: float,
    h_src: float,
    zoom_keys: Sequence[Sequence[Any]] | None,
    holds: Sequence[bool] | None,
    fps: float = 60.0,
    W: float = 1080,
    H: float = 1920,
    cx: float | None = 0.5,
    pan_x: float = 0.0,
    cam1_fit: float = 100.0,
    target: float | None = 0.5,
    smooth_s: float | None = 0.6,
    min_scale: float = 0.0,
    frame: dict[str, Any] | None = None,
    cam: int = 1,
) -> list[tuple[int, int | float]]:
    """Ключи слежения за головой по X для Камеры 1 или Камеры 2.

    Возвращает [(f, off), ...]. Ключ на каждом отсчёте, интерполяция LINEAR.

    `frame` — рамка кадра камеры 1 (`core/frame.py`: x/y/zoom + готовые dx/dy в px
    кадра), None — рамки нет. С рамкой слой клипа СМЕЩЁН и УВЕЛИЧЕН, поэтому края
    слоя и место головы считаются от смещённого слоя: зажим по центральному слою
    при рамке уводил бы край кадра внутрь (в кадре открывалась пустота).
    """
    cam_idx = cam - 1
    if not cams or len(cams) <= cam_idx or not pts or not w_src or not h_src:
        return []
    from core import headtrack

    fps = float(fps or 60.0)
    W = float(W)
    H = float(H)
    cx = float(cx if cx is not None else 0.5)
    pan_x = float(pan_x or 0.0)
    cam1_fit = float(cam1_fit or 100.0)
    target = float(target if target is not None else 0.5)
    smooth_s = max(0.01, float(smooth_s if smooth_s is not None else 0.6))
    min_scale = float(min_scale or 0.0)
    head_dead = HEAD_DEAD_RATIO * W

    # Рамка: множитель масштаба слоя и его сдвиг от центра кадра (px). Дефолт — 1 и 0,
    # то есть ровно прежний расчёт.
    fr = frame if isinstance(frame, dict) else {}
    frame_zoom = max(1.0, float(fr.get("zoom") or 100.0) / 100.0)
    frame_dx = float(fr.get("dx") or 0.0)

    fit_w = w_src * max(W / w_src, H / h_src) * (cam1_fit / 100.0) * frame_zoom
    Cx = cx * W

    raw_zoom = [(float(k[0]), float(k[1])) for k in (zoom_keys or []) if len(k) >= 2]
    # Влияния ease считаются один раз: значения кривой нужны на каждом отсчёте слежения.
    zoom_ease = _zoom_key_eases(zoom_keys or [])

    def _zoom_at(f: float) -> float:
        # Масштаб по кривой AE, а не по прямой: на участке с ease прямая даёт больше
        # настоящего (влияние in/out), и зажим по ней открывал край слоя — то же
        # значение считает превью (keysAt в static/app/85-inserts-view.js).
        return _zoom_scale_at(raw_zoom, f, ease=zoom_ease, holds=holds)

    def _clamp_off(off_val: float, s_val: float) -> float:
        # Края СЛОЯ: центр кадра плюс сдвиг рамки, полуширина — fit_w/2. Без рамки это
        # ровно прежние W/2 и fit_w.
        if s_val * fit_w < W:
            return 0.0
        left_edge = Cx + s_val * (W / 2.0 + frame_dx - fit_w / 2.0 - Cx) + pan_x
        right_edge = Cx + s_val * (W / 2.0 + frame_dx + fit_w / 2.0 - Cx) + pan_x
        min_off = W - right_edge
        max_off = -left_edge
        if min_off > max_off:
            return 0.0
        return max(min_off, min(max_off, off_val))

    segs = _show_segments(cams)
    shown_clips = []
    for cl in cams[cam_idx].get("clips", []):
        if not cl[4] or cl[1] <= cl[0]:
            continue
        for seg_start, seg_end, ci in segs:
            if ci != cam_idx:
                continue
            s_a = max(seg_start, cl[0])
            s_b = min(seg_end, cl[1])
            if s_b > s_a:
                shown_clips.append({
                    "start": s_a,
                    "end": s_b,
                    "cl_start": cl[0],
                    "cl_in": cl[2],
                })
    shown_clips.sort(key=lambda c: c["start"])
    if not shown_clips:
        return []

    step = max(1, int(round(fps / 10.0)))
    all_keys: list[tuple[float, float]] = []

    for clip in shown_clips:
        c_start = int(clip["start"])
        c_end = int(clip["end"])
        if c_end <= c_start:
            continue
        f_last = c_end - 1
        frames = list(range(c_start, c_end, step))
        if frames[-1] != f_last:
            frames.append(f_last)

        clip_samples: list[tuple[float, float]] = []
        y = 0.0
        prev_f = None

        # Худший (наименьший) масштаб на отрезке до СЛЕДУЮЩЕГО отсчёта слежения. Отсчёты
        # редкие (шаг ~0.1 с), а зум между ними бежит; зажим по масштабу текущего кадра
        # выпускал край слоя в кадр на промежуточных кадрах. Считается один раз на клип.
        seg_lo = [
            _zoom_min_scale(raw_zoom, frames[i], frames[i + 1], ease=zoom_ease, holds=holds)
            for i in range(len(frames) - 1)
        ]

        for i, f in enumerate(frames):
            t_src = (clip["cl_in"] + f - clip["cl_start"]) / fps
            hx = headtrack.head_at(pts, t_src)
            if hx is None:
                hx = 0.5
            s = _zoom_at(f)
            # Голова в системе слоя: сдвиг рамки входит слагаемым, увеличение — в fit_w
            X0 = W / 2.0 + frame_dx + (hx - 0.5) * fit_w
            screen = Cx + s * (X0 - Cx) + pan_x
            err = target * W - screen
            active = (s * 100.0) >= (min_scale - 1e-6)
            desired = err if active else 0.0
            # Зажим по ХУДШЕМУ масштабу обоих соседних отрезков: ключи слежения тоже
            # интерполируются Easy Ease, и границы применимы на всём отрезке — иначе
            # середина отрезка вылезает за зажим одного из его концов.
            s_lo = seg_lo[i] if i < len(seg_lo) else s
            if i and seg_lo[i - 1] < s_lo:
                s_lo = seg_lo[i - 1]

            if prev_f is None:
                y = _clamp_off(desired, s_lo)
            else:
                dt = (f - prev_f) / fps
                if active:
                    diff = err - y
                    if abs(diff) > head_dead:
                        sgn = 1.0 if diff > 0 else -1.0
                        y += (diff - sgn * head_dead) * (1.0 - math.exp(-dt / smooth_s))
                else:
                    y += (0.0 - y) * (1.0 - math.exp(-dt / smooth_s))
                    if abs(y) < 0.5:
                        y = 0.0
                y = _clamp_off(y, s_lo)

            clip_samples.append((f, y))
            prev_f = f

        all_keys.extend(clip_samples)

    return [(int(f), _r(off, 2)) for f, off in all_keys]

