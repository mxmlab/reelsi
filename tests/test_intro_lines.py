"""Перенос строк акцентов «текст за спиной»: ОДНО содержательное слово на строку.

Правило владельца (2026-10-17): служебное слово и число приклеиваются к СЛЕДУЮЩЕМУ слову, два
содержательных слова не склеиваются никогда («КРОВЬ / ГУСТЕЕТ»), служебное в самом конце группы
уходит к предыдущей строке. Замер архитектора на 49 группах владельца: 35 совпадений, 14
расхождений — одна из причин как раз склейка двух содержательных слов в одну строку.

Разбивка, которую присылала модель (lines), больше не используется: правило одно на всех.

Запуск: py -3.10 -m pytest tests/test_intro_lines.py -q
"""
import os
import sys

import pytest

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))

from core.aicut import commands  # noqa: E402


def _texts(ws, row_max=20):
    """Строки акцента как тексты: одна строка — слова через пробел."""
    return [" ".join(line) for line in commands._mid_lines(ws, row_max)]


# ---- примеры владельца: как он сам разбивал группы (строки через « / » в его записи) ----

@pytest.mark.parametrize("ws, want", [
    (["КРОВЬ", "ГУСТЕЕТ"], ["КРОВЬ", "ГУСТЕЕТ"]),
    (["МЯГКО", "ТОРМОЗИТ"], ["МЯГКО", "ТОРМОЗИТ"]),
    (["БОЛЬШОМ", "ГАЙДЕ"], ["БОЛЬШОМ", "ГАЙДЕ"]),
    (["ПАДАЕТ", "В", "НОЛЬ"], ["ПАДАЕТ", "В НОЛЬ"]),
    (["ТРЕМОР", "И", "ТУМАН"], ["ТРЕМОР", "И ТУМАН"]),
    (["СЕРЬЕЗНЫЕ", "ДЕНЬГИ", "ВПУСТУЮ"], ["СЕРЬЕЗНЫЕ", "ДЕНЬГИ", "ВПУСТУЮ"]),
    (["GLOBAL", "DRUG", "SURVEY"], ["GLOBAL", "DRUG", "SURVEY"]),
    (["ЗА", "48", "ЧАСОВ"], ["ЗА 48 ЧАСОВ"]),
    (["ПО", "8", "ЧАСОВ"], ["ПО 8 ЧАСОВ"]),
    (["СОХРАНИТЬ", "СВОЕ", "ЗДОРОВЬЕ"], ["СОХРАНИТЬ", "СВОЕ ЗДОРОВЬЕ"]),
    (["НА", "ЛИЧНОЕ", "ВЕДЕНИЕ"], ["НА ЛИЧНОЕ", "ВЕДЕНИЕ"]),
    (["54", "%"], ["54 %"]),
    (["РЕШАЕТ", "ЭТУ", "ПРОБЛЕМУ"], ["РЕШАЕТ", "ЭТУ ПРОБЛЕМУ"]),
    (["ТОЧКА", "ВХОДА"], ["ТОЧКА", "ВХОДА"]),
    (["ДЕЛАЕТЕ", "ЕСЛИ", "НЕ"], ["ДЕЛАЕТЕ ЕСЛИ НЕ"]),      # «ЕСЛИ НЕ» в конце — к предыдущей строке
    (["ЕСЛИ", "НЕ"], ["ЕСЛИ НЕ"]),                          # группа из одних служебных — одна строка
])
def test_примеры_владельца(ws, want):
    assert _texts(ws) == want


def test_кровь_густеет_две_строки():
    """Два содержательных слова — две строки. Склеивание «КРОВЬ ГУСТЕЕТ» — ошибка, которую замер поймал."""
    assert _texts(["КРОВЬ", "ГУСТЕЕТ"]) == ["КРОВЬ", "ГУСТЕЕТ"]


def test_служебное_и_число_приклеиваются_к_следующему_слову():
    """Цепочка: «ЗА» тянет «48», число тянет «ЧАСОВ» — всё в одну строку."""
    assert _texts(["ЗА", "48", "ЧАСОВ"]) == ["ЗА 48 ЧАСОВ"]


# ---- дорезка по потолку строки (ручка стиля) ----

def test_строка_длиннее_потолка_дорезается_по_словам():
    """Цепочка «ДА НА ОЧЕНЬ» (11 символов) при потолке 8 режется по словам; при потолке 100 — цела."""
    ws = ["ДА", "НА", "ОЧЕНЬ", "ДЛИННОЕ"]
    assert commands._mid_lines(ws, 8) == [["ДА"], ["НА", "ОЧЕНЬ"], ["ДЛИННОЕ"]]
    assert commands._mid_lines(ws, 100) == [["ДА", "НА", "ОЧЕНЬ"], ["ДЛИННОЕ"]]


# ---- cmd_intro: разбивка из ответа модели не применяется ----

def test_lines_модели_не_влияют_на_перенос(tmp_path, monkeypatch):
    """Модель прислала lines [2] на «КРОВЬ ГУСТЕЕТ» — две строки всё равно: правило одно."""
    names = ["ПРИВЕТ", "ДРУЗЬЯ", "КРОВЬ", "ГУСТЕЕТ", "СЕГОДНЯ"]
    words = [(i, w, i * 0.5, i * 0.5 + 0.4) for i, w in enumerate(names)]
    monkeypatch.setattr(commands, "_words_from_xml", lambda _p: words)
    groups = [{"from": 2, "count": 2, "color": "white", "back": False, "lines": [2], "enum": False}]
    monkeypatch.setattr(commands, "_ask_json",
                        lambda *a, **k: {"intro_rows": [], "mid_groups": groups})
    res = commands.cmd_intro(str(tmp_path / "clip.xml"), emit=lambda *a, **k: None, inserts=[])
    assert [(m["from"], m["count"], m["break"]) for m in res["mid_groups"]] == [(2, 1, True), (None, 1, False)]
    assert all("lines" not in m for m in res["mid_groups"])
