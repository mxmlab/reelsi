def main():
    have = {}
    if os.path.exists(EN):
        have = json.load(io.open(EN, encoding="utf-8"))
    added = 0
    for k, v in ADDITIONS.items():
        if k in have and have[k] != "":
            continue
        if not str(v).strip():
            raise SystemExit(f"пустой перевод для {k!r} — не пишем пустоту")
        have[k] = v
        added += 1
    with io.open(EN, "w", encoding="utf-8") as f:
        json.dump(have, f, ensure_ascii=False, indent=2, sort_keys=True)
        f.write("\n")
    print(f"добавлено ключей: {added}, всего: {len(have)}")
    return 0


