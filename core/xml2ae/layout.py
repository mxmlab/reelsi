def _phrase_strength(members: Sequence[int], scores: Mapping[int, float] | None) -> float | None:
    """Сила фразы: максимум сил её слов. None — силы ни у одного слова нет.

    Максимум, а не среднее: фраза сильна самым сильным словом, и наезд приходит на неё
    целиком. Слово без посчитанной силы (его не было в сайдкаре) сильным не считается.
    """
    if not scores:
        return None
    vals = [float(scores[i]) for i in members if i in scores]
    return max(vals) if vals else None


def _percentile(values: Sequence[float], pct: float) -> float:
    """Значение p-го процентиля (линейная интерполяция, как `numpy.percentile`).

    Порог силы задан процентами (ручка «Порог силы, %»), и мерить его надо по шкале
    САМОГО КЛИПА: 50 — медиана жёлтых, 70 — дефолт (p70 по замеру 02.10.2026), 0 — минимум
    («ниже порога не бывает никто, наезжают все жёлтые»), 100 — максимум (проходит только
    самое сильное слово клипа). Интерполяция — как у медианы: для чётного числа
    значений медиана тоже лежит между двумя средними, и сравнение `s >= порог` из WX
    повторяется ровно. Пустой список даёт 0 (деления на ноль нет).
    """
    if not values:
        return 0.0
    srt = sorted(float(v) for v in values)
    p = max(0.0, min(100.0, float(pct)))
    pos = (len(srt) - 1) * p / 100.0
    lo = int(math.floor(pos))
    hi = int(math.ceil(pos))
    if lo == hi:
        return srt[lo]
    return srt[lo] + (srt[hi] - srt[lo]) * (pos - lo)


def _yellow_strong_phrases(pairs: Sequence[tuple[tuple[float, float], float]],
                           clip_scores: Sequence[float], min_pct: float,
                           max_per_piece: int, second_min_s: float,
                           seg_len_frames: float, fps: float
                           ) -> list[tuple[float, float]]:
    """Отобрать фразы для наезда по силе: только прошедшие порог, не больше N.

    `pairs` — [(фраза (t_start, t_end) в кадрах, её сила)] для фраз, ЗВУЧАЩИХ в куске;
    силу фразы считает камера (`plan_camera`, `_take_yellow`): это максимум сил её слов,
    и второй копии группировки «подряд идущие слова — одна фраза» здесь не заводится.

    `clip_scores` — силы ВСЕХ жёлтых слов КЛИПА (а не куска): «жёлтых много» — свойство
    ролика, и фраза НИЖЕ `min_pct`-го процентиля сил жёлтых клипа не наезжает вовсе.
    `min_pct` = 70 (дефолт) — p70 жёлтых клипа (замер 02.10.2026); 0 — наезжают все фразы;
    100 — только самое сильное слово клипа. Пусто — порог 0 (вызов без камеры, тесты).

    `max_per_piece` — сколько наездов максимум на кусок (1..3), `second_min_s` — с какой
    длины куска разрешён ВТОРОЙ наезд: хвост правила прежний — третий и следующие циклы
    идут только в кусок, куда они помещаются, а между наездами обязан влезть отъезд.
    Возвращает фразы в порядке времени: циклы считаются по монтажу, не по силе (иначе
    состояние «камера уже на пике» считалось бы неверно).
    """
    threshold = _percentile(clip_scores if clip_scores else [x for _p, x in pairs],
                            float(min_pct))
    strong = [(s, ph) for ph, s in pairs if float(s) >= threshold]
    cap = int(max_per_piece) if seg_len_frames >= float(second_min_s) * float(fps) else 1
    top = [ph for _s, ph in sorted(strong, key=lambda sp: (-sp[0], sp[1][0]))[:max(1, cap)]]
    top.sort()
    return top


def _median(vals: Sequence[float]) -> float:
    """Медиана значений (пусто — 0.0): порог «слабого» слова."""
    if not vals:
        return 0.0
    srt = sorted(float(v) for v in vals)
    n = len(srt)
    return srt[n // 2] if n % 2 else (srt[n // 2 - 1] + srt[n // 2]) / 2.0


def _build_take_cycle(
    ph: tuple[float, float] | None,
    cur_ref: int,
    seg_end: int,
    fps: float,
    nom_hold_s: float,
    is_seg_start: bool,
    nom_out_s: float = 2.4,
) -> tuple[int, int, int, int | None] | None:
    """Расчёт временных точек одного цикла наезда (a, b, c, d) в кадрах.

    a — старт подъезда, b — пик, c — старт отъезда, d — возврат (None — отъезда нет).
    `ph` — ФРАЗА хайлайта (t_start, t_end) в кадрах: начало первого слова и конец
    последнего. Подъезд начинается за TAKE_YELLOW_LEAD_S до фразы и длится
    TAKE_YELLOW_IN_S — пик приходит ВНУТРЬ фразы. Раньше `cur_ref` (импульс склейки или
    отъезд прошлого цикла + 1 с) наезд не начинается: старт подтягивается к `cur_ref`, а
    фраза, которая вместе с удержанием кончилась до этого момента, пропускается —
    наезжать уже не на что. Удержание считается сверх КОНЦА фразы
    (c = max(t_end, b) + hold_s), а отъезд ставится, только если целиком помещается до
    конца куска (минус хвост): не помещается — d = None, и камера держит пик до склейки.
    Сжатия отъезда до TAKE_MIN_OUT_S больше нет.
    `ph is None` — свободный цикл со сжатием по правилам (легаси-ветка).
    Возвращает None, если цикл не помещается.
    """
    if ph is not None:
        t_start, t_end = float(ph[0]), float(ph[1])
        hold_f = round(nom_hold_s * fps)
        a = int(round(t_start - TAKE_YELLOW_LEAD_S * fps))
        if a < cur_ref:
            # Камера ещё занята прошлым циклом (отъезд + 1 с — «повтор не раньше 1 с»):
            # наезд начнётся, как только она освободится, но только если фраза с её
            # удержанием к тому моменту не кончилась — иначе наезжать не на что.
            if int(round(t_end)) + hold_f < cur_ref:
                return None
            a = cur_ref
        tail_f = round(TAKE_MIN_TAIL_S * fps)
        in_f = round(TAKE_YELLOW_IN_S * fps)
        if a + in_f > seg_end - tail_f:
            # Полного подъезда до конца куска не хватает — сжимаем до минимального.
            in_f = round(TAKE_MIN_IN_S * fps)
        b = a + in_f
        if b > seg_end - tail_f:
            return None
        c = max(int(round(t_end)), b) + hold_f
        d_full = c + round(nom_out_s * fps)
        d: int | None = None if d_full > seg_end - tail_f else d_full
        return (a, b, c, d)

    avail = (seg_end - cur_ref) / fps
    min_lead_s = TAKE_MIN_LEAD_S if is_seg_start else 0.0
    min_needed = min_lead_s + TAKE_MIN_IN_S + TAKE_MIN_HOLD_S + TAKE_MIN_OUT_S + TAKE_MIN_TAIL_S
    if avail < min_needed:
        return None

    nom_lead = TAKE_LEAD_S if is_seg_start else 0.0
    lead_dur = nom_lead
    in_dur = TAKE_IN_S
    hold_dur = nom_hold_s
    out_dur = nom_out_s
    tail_dur = TAKE_TAIL_S
    total_nom = lead_dur + in_dur + hold_dur + out_dur + tail_dur

    if avail < total_nom:
        deficit = total_nom - avail
        # 1) tail: 2.0 -> 0.3
        tail_shrink = min(deficit, tail_dur - TAKE_MIN_TAIL_S)
        tail_dur -= tail_shrink
        deficit -= tail_shrink
        # 2) lead: 1.6 -> min_lead_s
        lead_shrink = min(deficit, max(0.0, lead_dur - min_lead_s))
        lead_dur -= lead_shrink
        deficit -= lead_shrink
        # 3) in and out: сжимаем до 0.5
        in_avail = max(0.0, in_dur - TAKE_MIN_IN_S)
        out_avail = max(0.0, out_dur - TAKE_MIN_OUT_S)
        shrink_each = deficit / 2.0
        in_shrink = min(shrink_each, in_avail)
        out_shrink = min(shrink_each, out_avail)
        in_dur -= in_shrink
        out_dur -= out_shrink
        deficit -= (in_shrink + out_shrink)
        if deficit > 1e-4 and out_dur > TAKE_MIN_OUT_S:
            extra = min(deficit, out_dur - TAKE_MIN_OUT_S)
            out_dur -= extra
            deficit -= extra
        elif deficit > 1e-4 and in_dur > TAKE_MIN_IN_S:
            extra = min(deficit, in_dur - TAKE_MIN_IN_S)
            in_dur -= extra
            deficit -= extra
        # 4) hold: nom_hold_s -> 0.3
        hold_shrink = min(deficit, max(0.0, hold_dur - TAKE_MIN_HOLD_S))
        hold_dur -= hold_shrink
        deficit -= hold_shrink
        if deficit > 1e-4:
            return None

    a = cur_ref + round(lead_dur * fps)
    b = a + round(in_dur * fps)
    c = b + round(hold_dur * fps)
    d = c + round(out_dur * fps)
    if d > seg_end - round(TAKE_MIN_TAIL_S * fps):
        return None
    return (a, b, c, d)


def _build_center_take_cycle(
    span_start: int,
    span_end: int,
    fps: float,
    nom_hold_s: float,
    nom_out_s: float,
    is_seg_start: bool,
    is_seg_end: bool,
    strict: bool = False,
) -> tuple[int, int, int, int | None] | None:
    """Расчёт свободного цикла наезда с центром удержания в середине промежутка [span_start, span_end].

    Центр удержания = round((span_start + span_end) / 2.0).
    При нехватке места подъезд и удержание сжимаются с сохранением центра; отъезд не
    сжимается вовсе — не помещается целиком, значит его нет (d = None, камера держит
    пик до конца промежутка).
    Если strict=True, дефициты не сжимаются, сразу None.
    Если цикл не помещается — возвращает None.
    """
    fps = float(fps)
    mid = round((span_start + span_end) / 2.0)

    min_lead_frames = round(TAKE_MIN_LEAD_S * fps) if is_seg_start else 0
    min_tail_frames = round(TAKE_MIN_TAIL_S * fps) if is_seg_end else 0

    min_a = span_start + min_lead_frames
    max_d = span_end - min_tail_frames

    in_dur = TAKE_IN_S
    out_dur = nom_out_s
    hold_dur = nom_hold_s

    hold_f = round(hold_dur * fps)
    half_h = round(hold_f / 2.0)
    b = mid - half_h
    c = b + hold_f
    a = b - round(in_dur * fps)
    d = c + round(out_dur * fps)

    def_l = max(0, min_a - a)
    def_r = max(0, d - max_d)

    if strict:
        return None if (def_l > 0 or def_r > 0) else (a, b, c, d)

    if def_l > 0:
        in_shrink_frames = min(def_l, round(max(0.0, in_dur - TAKE_MIN_IN_S) * fps))
        in_dur -= in_shrink_frames / fps
        def_l -= in_shrink_frames

    # Отъезд НЕ сжимается (задание «отъезд, только если помещается»): не влез целиком —
    # отъезда нет, камера держит пик до конца промежутка. Поэтому дефицит справа
    # удержание не урезает: сжатие удержания осталось только под левый край.
    if def_l > 0:
        hold_shrink_f = min(def_l * 2, round(max(0.0, hold_dur - TAKE_MIN_HOLD_S) * fps))
        hold_dur -= hold_shrink_f / fps
        def_l = max(0, def_l - round(hold_shrink_f / 2.0))

    if def_l > 0:
        return None

    hold_f = round(hold_dur * fps)
    half_h = round(hold_f / 2.0)
    b = mid - half_h
    c = b + hold_f
    a = b - round(in_dur * fps)
    d_full = c + round(out_dur * fps)

    if a < min_a:
        return None
    d_out: int | None = None if d_full > max_d else d_full

    return (a, b, c, d_out)


def _take_zoom_segment_keys(
    f: int,
    seg_end: int,
    v: float,
    fps: float,
    take: dict[str, Any],
    trng: Any,
    lead_min_frame: int,
) -> list[tuple[float, float, int, int]]:
    """Ключи наезда в тейке внутри отрезка [f, seg_end] для любого режима зума.

    Цикл наезда — подъезд (a), пик (b) и, ТОЛЬКО если полный отъезд помещается до конца
    куска, отъезд (c, d). Цикл без отъезда отдаёт два ключа: пик держится до склейки
    (у ключа b hold=1 — значение стоит до следующего ключа).
    `take["words"]` — ФРАЗЫ (t_start, t_end) в кадрах: начало первого и конец последнего
    слова (легаси-число читается как односложная фраза). Поддерживает независимые блоки:
    - yellow_zoom: наезд на фразы хайлайта в любом куске. При `take["yellow_strong"]` и
      силах фраз `take["yellow_strengths"]` (плюс силы всех жёлтых клипа
      `take["yellow_clip_scores"]`) наезд ставится только на САМЫЕ СИЛЬНЫЕ фразы, а
      фраза ниже порога силы клипа не наезжает вовсе: жёлтых много, и наезд на каждом
      держал камеру приближенной весь ролик (решение владельца 02.10.2026). Сила фразы —
      максимум сил слов, которые в неё попали (считает камера). Порог силы
      (`yellow_min_pct`), предел наездов на кусок (`yellow_max_per_piece`) и порог длины
      для второго наезда (`yellow_second_min_s`) — ручки стиля;
    - take_zoom (long_on): наезд в длинном куске (>= min_s), центр удержания в середине куска/промежутка.
    """
    fps = float(fps)
    min_s = float(take.get("min_s", 8.0))

    raw_words = take.get("words") or []
    # Силы фраз (`take["yellow_strengths"]`, параллельно `words`) — для правила «наезд
    # только на сильные жёлтые»: считает их камера (`plan_camera`), знающая состав фраз.
    raw_strengths = list(take.get("yellow_strengths") or [])
    phrases: list[tuple[float, float]] = []
    strengths: list[float] = []
    for _k, _w in enumerate(raw_words):
        if isinstance(_w, (tuple, list)):
            _ts = float(_w[0])
            _te = float(_w[1]) if len(_w) > 1 else _ts
        else:
            _ts = _te = float(_w)              # легаси: время начала = односложная фраза
        # Фраза берётся куском, если она в нём ЗВУЧИТ (пересекается с ним): фраза,
        # начавшаяся до склейки, доигрывает и в этом куске — иначе хайлайт на стыке
        # кусков не наезжал бы вовсе.
        if _ts < seg_end and _te > f:
            phrases.append((_ts, _te))
            strengths.append(float(raw_strengths[_k])
                             if _k < len(raw_strengths) and raw_strengths[_k] is not None
                             else 0.0)
    order = sorted(range(len(phrases)), key=lambda k: phrases[k])
    phrases = [phrases[k] for k in order]
    strengths = [strengths[k] for k in order]
    seg_words = [p[0] for p in phrases]

    long_on = take.get("long_on")
    yellow_on = take.get("yellow_on")
    if yellow_on is None:
        if "yellow_zoom" in take:
            yellow_on = bool(take["yellow_zoom"])
        elif "yellow_mode" in take:
            yellow_on = take["yellow_mode"] in ("snap", "only")
        elif raw_words:
            yellow_on = True
        else:
            yellow_on = False

    if long_on is None:
        if "take_zoom" in take:
            long_on = bool(take["take_zoom"])
        elif take.get("yellow_mode") == "only":
            long_on = False
        elif take.get("yellow_mode") == "snap":
            long_on = not bool(seg_words)
        else:
            long_on = True

    if not yellow_on and not long_on:
        return []

    # Кусок короче min_s — длинный наезд выключен; если жёлтые тоже выкл — наездов нет
    if not yellow_on and (seg_end - f) < min_s * fps:
        return []

    take_lo = float(take.get("lo", 25.0))
    take_hi = float(take.get("hi", 40.0))
    nom_hold_s = float(take.get("hold_s", 2.0))
    nom_out_s = float(take.get("out_s", 2.4))
    tail_f = round(TAKE_MIN_TAIL_S * fps)
    yellow_cycles: list[tuple[int, int, int, int | None]] = []
    if yellow_on:
        # «Наезд только на сильные жёлтые»: силы фраз из сайдкара (core/emphasis.py) и
        # силы всех жёлтых КЛИПА (их считает камера). Флаг ставит plan_camera по галке
        # стиля; нет сил — правило прежнее (наезд на каждую фразу). Порог силы, предел
        # наездов на кусок и порог длины для второго наезда — ручки стиля
        # (plan_camera кладёт их в `take`), константы ниже — их дефолты.
        if take.get("yellow_strong") and raw_strengths:
            phrases = _yellow_strong_phrases(
                list(zip(phrases, strengths)),
                take.get("yellow_clip_scores") or [],
                float(take.get("yellow_min_pct", HL_ZOOM_MIN_PCT)),
                int(take.get("yellow_max_per_piece", HL_ZOOM_MAX_PER_PIECE)),
                float(take.get("yellow_second_min_s", HL_ZOOM_SECOND_MIN_S)),
                seg_end - f, fps)
        cur_ref = lead_min_frame
        is_seg_start = True
        for _ts, _te in phrases:
            if yellow_cycles and yellow_cycles[-1][3] is None:
                # Камера ещё на пике прошлой фразы и отъезда не было: второго наезда не
                # ставим — удержание продлевается до конца этой фразы + «Держать, с»,
                # а отъезд решается по тому же правилу (влезает целиком или нет).
                _pa, _pb, _pc, _ = yellow_cycles[-1]
                _c = max(_pc, int(round(_te)) + round(nom_hold_s * fps))
                _d_full = _c + round(nom_out_s * fps)
                _d: int | None = None if _d_full > seg_end - tail_f else _d_full
                yellow_cycles[-1] = (_pa, _pb, _c, _d)
                continue
            cycle = _build_take_cycle((_ts, _te), cur_ref, seg_end, fps, nom_hold_s, is_seg_start, nom_out_s=nom_out_s)
            if cycle is not None:
                yellow_cycles.append(cycle)
                cur_ref = (cycle[3] if cycle[3] is not None else cycle[2]) + round(1.0 * fps)
                is_seg_start = False

    long_cycle: tuple[int, int, int, int | None] | None = None
    if long_on and (seg_end - f) >= min_s * fps - 1e-4:
        if not yellow_cycles:
            long_cycle = _build_center_take_cycle(lead_min_frame, seg_end, fps, nom_hold_s, nom_out_s, is_seg_start=True, is_seg_end=True)
        else:
            spans: list[tuple[int, int, bool, bool]] = []
            # 1) До первого жёлтого цикла
            first_a = yellow_cycles[0][0]
            s0_end = first_a - round(1.0 * fps)
            if s0_end > lead_min_frame:
                spans.append((lead_min_frame, s0_end, True, False))
            # 2) Между жёлтыми циклами
            for i in range(len(yellow_cycles) - 1):
                _prev_d = yellow_cycles[i][3]
                if _prev_d is None:
                    break                      # без отъезда бывает только последний цикл
                s_st = _prev_d + round(1.0 * fps)
                s_en = yellow_cycles[i + 1][0] - round(1.0 * fps)
                if s_en > s_st:
                    spans.append((s_st, s_en, False, False))
            # 3) После последнего жёлтого цикла
            last_d = yellow_cycles[-1][3]
            if last_d is not None:
                send_st = last_d + round(1.0 * fps)
                if seg_end > send_st:
                    spans.append((send_st, seg_end, False, True))

            if spans:
                for st, en, is_start, is_end in sorted(spans, key=lambda s: s[1] - s[0], reverse=True):
                    cand = _build_center_take_cycle(st, en, fps, nom_hold_s, nom_out_s, is_start, is_end, strict=True)
                    if cand is not None:
                        long_cycle = cand
                        break

    all_cycles = list(yellow_cycles)
    if long_cycle is not None:
        all_cycles.append(long_cycle)
    all_cycles.sort(key=lambda c: c[0])

    out_keys: list[tuple[float, float, int, int]] = []
    for a, b, c, d in all_cycles:
        dm = trng.uniform(take_lo, take_hi) if trng else 25.0
        vm = round(v * (1.0 + dm / 100.0), 1)
        out_keys.extend([
            (float(a), v, 1, 0),
            (float(b), vm, 2, 1),
        ])
        if d is not None:
            out_keys.extend([
                (float(c), vm, 3, 0),
                (float(d), v, 3, 1),
            ])

    return out_keys


def _cam1_zoom_keys(cams: Sequence[dict[str, Any]], big: float = ZOOM_BIG, small: float = ZOOM_SMALL, punch: int = ZOOM_PUNCH,
                    lo: float = 112.0, hi: float = 140.0, fps: float = 60.0, start: bool = True,
                    cam: int = 0, take: dict[str, Any] | None = None) -> list[Any]:
    """Кейфреймы зума Null Камеры (cam=0 для Камеры 1, cam=1 для Камеры 2).
    Мультикам -> импульс-наезд на каждом ВОЗВРАТЕ кам2→кам1 (при cam=0) или на каждом
    ВХОДЕ кам1→кам2 (при cam=1).
    ПЕРВЫЙ импульс = `big` (крупный наезд в начале / при первом входе), последующие возвраты/входы =
    случайный пик в [lo,hi]% (не 182 каждый раз — юзер задавал интервал), всегда откат к `small` (100).
    Если start=False — в первом срезе один ключ с small (100) без наезда и отката.
    Одна камера (перебивок нет): для cam=0 -> фиксированный DEFAULT_CAM1_SCALE (если take=None),
    для cam>0 -> пустой список.
    При переданном `take` добавляются наезды в длинных тейках.
    -> [(frame, percent, ...), ...]."""
    import random as _rnd
    fps = float(fps) or 60.0
    punch = int(punch)
    if cam == 0:
        returns = _cam1_return_frames(cams)              # срезы перебивка→кам1 (реальные смены кадра)
        if not returns and take is None:                 # одна камера без наездов — фикс-паттерн
            k = float(fps) / 60.0
            return [(round(f * k, 2), v) for f, v in DEFAULT_CAM1_SCALE]
        frames = sorted(set([0] + returns))
        seed = ",".join(str(f) for f in frames)
    else:
        segs = _show_segments(cams)
        entries = [s[0] for s in segs if s[2] == cam and s[1] > s[0]]
        if not entries:
            return []
        frames = sorted(set(entries))
        seed = f"c{cam + 1}," + ",".join(str(f) for f in frames)

    rng = _rnd.Random(seed)          # тот же таймлайн -> тот же разброс
    if take is None:
        keys_2: list[tuple[float, float]] = []
        prev = None
        for idx, t in enumerate(frames):
            if idx == 0:
                if not start:
                    keys_2.append((t, small))
                    continue
                peak = big
            else:
                for _ in range(8):
                    peak = round(rng.uniform(lo, hi), 1)
                    if prev is None or abs(peak - prev) >= 8:
                        break
                prev = peak
            keys_2.append((t, peak))
            keys_2.append((t + punch, small))
        return keys_2

    # take is not None:
    tseed = ("t," if cam == 0 else f"t{cam + 1},") + ",".join(str(f) for f in frames)
    trng = _rnd.Random(tseed)
    segs = _show_segments(cams)
    cam_segs = [(s[0], s[1]) for s in segs if s[2] == cam and s[1] > s[0]]
    if not cam_segs and cam == 0:
        dur = max((cl[1] for c in cams for cl in c["clips"] if cl[4]), default=fps * 10)
        cam_segs = [(0.0, float(dur))]
    keys_4: list[tuple[float, float, int, int]] = []
    prev_peak = None
    for idx, (s0, s1) in enumerate(cam_segs):
        s0_i = int(round(s0))
        s1_i = int(round(s1))
        if idx == 0 and s0_i == 0:
            if not start:
                # «Первый наезд» снят, но движение в тейке начинается ОТ этого ключа:
                # 1 — источник движения (out эталонной кривой), 0 остаётся за дрейфом.
                keys_4.append((float(s0_i), small, 1, 0))
                pe = None
            else:
                pe = min(punch, max(1, s1_i - s0_i - 2))
                keys_4.append((float(s0_i), big, 1, 0))
                keys_4.append((float(s0_i + pe), small, 2, 0))
        else:
            for _ in range(8):
                peak = round(rng.uniform(lo, hi), 1)
                if prev_peak is None or abs(peak - prev_peak) >= 8:
                    break
            prev_peak = peak
            pe = min(punch, max(1, s1_i - s0_i - 2))
            keys_4.append((float(s0_i), peak, 1, 0))
            keys_4.append((float(s0_i + pe), small, 2, 0))

        lead_min_frame = (s0_i + pe + 1) if pe is not None else s0_i
        t_keys = _take_zoom_segment_keys(s0_i, s1_i, v=small, fps=fps, take=take, trng=trng, lead_min_frame=lead_min_frame)
        keys_4.extend(t_keys)
    return keys_4


def _cam1_jump_keys(cams: Sequence[dict[str, Any]], lo: float = 100.0, hi: float = 140.0, min_diff: float = 12.0, fps: float = 60.0, start: bool = True,
                    big: float | None = ZOOM_BIG, punch: int | None = ZOOM_PUNCH, take: dict[str, Any] | None = None,
                    cam: int = 0) -> list[tuple[float, float, int, int]]:
    """Джамп-кат зум (cam=0 для Камеры 1, cam=1 для Камеры 2): скейл ПРЫГАЕТ на случайное
    значение 100–140%% (HOLD-кейфреймы) на срезах показа соответствующей камеры.
    Первый срез со start=True: плавный наезд big→100 за punch кадров (ease out 35 / in 90).
    Стартовое значение — всегда 100 % (small).
    Если big == 100 (наезжать некуда) или start=False — один ключ 100 % без наезда.
    В длинных тейках (seg_end - f >= take['min_s']*fps) при переданном take:
    плавный подъезд к v*m, удержание take['hold_s'] с, отъезд обратно к v.
    Возвращает 4-элементные ключи: [(frame, pct, mode, hold), ...].
    Детерминировано (seed от кадров реза)."""
    import random as _rnd
    fps = int(round(float(fps) or 60))
    big = float(big if big is not None else ZOOM_BIG)
    small = 100.0                                 # то же, что ZOOM_SMALL у pulse: возврат всегда в 100 %
    punch = int(punch if punch is not None else ZOOM_PUNCH)
    frames, seg_ends = _camera_cut_segments(cams, cam=cam, fps=fps)
    if not frames:
        return []
    seed = ("" if cam == 0 else f"j{cam + 1},") + ",".join(str(f) for f in frames)
    tseed = ("t," if cam == 0 else f"t{cam + 1},") + ",".join(str(f) for f in frames)
    rng = _rnd.Random(seed)
    trng = _rnd.Random(tseed) if take else None
    keys, prev = [], None
    for idx, f in enumerate(frames):
        seg_end = int(round(seg_ends[idx]))
        if idx == 0:
            v = small
        else:
            for _ in range(8):
                v = round(rng.uniform(lo, hi), 1)
                if prev is None or abs(v - prev) >= min_diff:
                    break
        prev = v

        if idx == 0:
            if not start or big == small:
                keys.append((f, small, 0, 1))
                pe = None
            else:
                pe = min(punch, max(1, seg_end - int(round(f)) - 2))
                keys.append((f, big, 1, 0))
                keys.append((f + pe, small, 2, 1))
        else:
            keys.append((f, v, 0, 1))
            pe = None

        if take is not None:
            lead_min_frame = (f + pe + 1) if (idx == 0 and start and pe is not None) else f
            t_keys = _take_zoom_segment_keys(int(round(f)), seg_end, v, float(fps), take, trng, int(round(lead_min_frame)))
            keys.extend(t_keys)
    return keys


