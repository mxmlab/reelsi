# (hl_dur), а короткие слова — своё hd.
HL_DUR = 0.35
HL_FIT = 0.6


def hl_appear_dur(vis: float | int) -> float:
    """Длительность появления жёлтого слова, с: min(HL_DUR, HL_FIT*vis).
    vis — видимое время слова (outPoint − момент появления), с. Округление до десятых
    миллисекунды: столько же знаков, сколько у остальных чисел плана и .jsx."""
    return round(min(HL_DUR, HL_FIT * float(vis)), 4)


# ---- Блюр появления: «Blurriness» AE против сигмы CSS blur() --------------------
# Сила размытия в AE и в CSS меряется РАЗНЫМИ числами: у Gaussian Blur это «Blurriness»
# (радиус), у CSS blur() — сигма гауссианы. В .jsx уезжает значение стиля как есть (его
# читает AE), а превью рисует блюр CSS-ом и обязано перевести — без перевода слово
# выходило вчетверо размытее собранного в AE: на 29.3 с «КУБИК» в нашей сборке не
# читался вовсе, в AE буквы стояли уже резкими.
#
# Число — замер по эталонному рендеру (C1476, 29.17–29.52 с, слово «КУБИК»): подгонка
# размытия по кадрам даёт sigma = Blurriness / 4.2 на всём ходу появления (Blurriness
# от 5 до 49), а отношение «наш блюр / блюр AE» на одних и тех же кадрах — 4.2–4.4.
# Метод проверен подстановкой: опорный кадр, размытый на известную сигму, подгонка
# возвращает ту же сигму.
AE_BLUR_PER_SIGMA = 4.2


def css_blur_px(amt: Any) -> float:
    """Сила блюра AE -> пиксели CSS ``blur()``: сигма = Blurriness / AE_BLUR_PER_SIGMA.

    Число ОДНО на всю сборку: его кладёт в план scene_plan, а превью берёт готовым —
    своей копии перевода у JS нет (как и у остальной геометрии субтитров). Ноль, пусто
    и мусор дают 0.0: блюра нет, и «не задано» совпадает с «выключено» — та же
    терпимость, что у hl_size_factor.
    """
    try:
        return round(float(amt) / AE_BLUR_PER_SIGMA, 2)
    except (TypeError, ValueError):
        return 0.0


# ---- Кегль жёлтого слова: множитель относительно базового (ручка hl_size_k) ------
# У жёлтых своя семья ручек (hl_font — начертание, hl_bold — fauxBold, hl_fill — цвет,
# hl_row_anim/hl_row_stack — поведение в строке, hl_blur/hl_blur_amt — появление,
# hl_rise/hl_dur/hl_step — геометрия), а РАЗМЕРА среди них не было: жёлтое слово
# рисовалось общим FONT_SIZE, как белое. Контраст размера («editorial-emphasis»
# каталога) — ровно эта недостающая ручка: множитель базового кегля.
def hl_size_factor(k: Any) -> float:
    """Множитель кегля жёлтого слова: ``hl_size_k`` -> безопасное для сборки число.

    Ноль, пусто и мусор в стиле дают 1.0: слово нулевого кегля не бывает, и «не
    задано» обязано совпасть с «как сегодня» — иначе правка стиля руками молча
    стирала бы жёлтые слова с экрана."""
    try:
        f = float(k)
    except (TypeError, ValueError):
        return 1.0
    return f if f > 0 else 1.0


def hl_size_expr(k: Any, base: str, flag: str | None = None) -> str:
    """Кегль жёлтого слова в шаблоне .jsx: при k = 1.0 — ровно ``base``.

    Своей копии множителя в шаблоне нет: HL_SIZE_K объявляется ОДИН раз
    (``hl_size_decl``), а выражение подставляется туда, где цикл ставит кегль.
    ``flag`` — имя признака «слово жёлтое» в этом цикле: строка кегля общая с белыми
    словами, и множитель обязан применяться только к жёлтым. Без признака (циклы,
    где слова ТОЛЬКО жёлтые) выражение проще. При 1.0 — ни множителя, ни признака:
    .jsx со стилем по умолчанию остаётся прежним байт в байт (golden_geometry.jsx).
    """
    if hl_size_factor(k) == 1.0:
        return base
    if flag:
        return "(%s?%s*HL_SIZE_K:%s)" % (flag, base, base)
    return "%s*HL_SIZE_K" % base


def hl_size_decl(k: Any) -> str:
    """Объявление HL_SIZE_K в шапке .jsx; при 1.0 — пусто (эталон не меняется).

    Число одно на всю сборку: кегль ставится в нескольких циклах субтитров, и своя
    копия множителя в каждом разошлась бы с остальными молча."""
    f = hl_size_factor(k)
    if f == 1.0:
        return ""
    return ("\n    var HL_SIZE_K = %g;   // кегль жёлтого слова относительно базового"
            " (стиль hl_size_k): 1 = общий FONT_SIZE" % f)


# ---- Появление БАЗОВОГО (белого) слова: пресет стиля sub_anim ------------------
# Слово белого субтитра в AE не анимируется вовсе (posP.setValue([SW/2, POSY])) —
# в отличие от жёлтого, у которого своя анимация появления (HL_RISE/HL_DUR/блюр).
# Пресет добавляет ключи ПОЯВЛЕНИЯ белому слову: положение, масштаб, прозрачность и
# блюр — всё, что переводится в AE один к одному (класс А каталога HyperFrames).
# Код оттуда НЕ копируется: берём идею и параметры.
#
# Кривые считает ТОЛЬКО этот модуль: план несёт готовые ключи, а .jsx и предпросмотр
# (85-inserts-view.js) их читают и интерполируют — .jsx кривой easePair (те же 35/90,
# что у жёлтых), превью тем же keysAt. Второй копии формулы нет ни в ExtendJS, ни в JS.
#
# Длительность по умолчанию — у КАЖДОГО пресета своя (у rise 0.18 с, у pop 0.2 с):
# это часть пресета, а не общая ручка стиля. Ключ стиля sub_anim_dur = 0 (и ключа нет)
# значит «как задумано пресетом»; любое другое число перебивает его.
# Амплитуда (sub_anim_amt) — то же правило, но смысл у пресетов разный: у подъёма это
# пиксели кадра (их уже умножил вид «size» — core/style_geometry — второй раз не множим),
# у роста — стартовый масштаб в процентах. Пусто (None) — число пресета.
SUB_ANIM_PRESETS: dict[str, dict[str, float]] = {
    "rise": {"dur": 0.18, "amt": 120.0},   # «Per Word Rise»: въезд снизу
    # «Pop»: слово вырастает от стартового размера к пику 108 % и обратно к 100 %.
    # Амплитуда здесь — СТАРТОВЫЙ масштаб в процентах, а не пиксели: рост переводится
    # в AE один к одному, а «на сколько пикселей выросло слово» зависит от кегля
    # строки, которого пресет не знает. 50 — заметный рост у субтитров 1080: 100 − 50.
    "pop": {"dur": 0.2, "amt": 50.0},
    # «Clip Wipe»: слово открывается слева направо — доля открытия 0 -> 100 % за dur.
    # Амплитуды у пресета нет вовсе, и sub_anim_amt он не читает: открытие всегда
    # полное (недооткрытое слово осталось бы обрезанным навсегда).
    "wipe": {"dur": 0.25},
    # «Weight Shift»: слово приходит ТОНКИМ начертанием (sub_anim_font) и в середине
    # dur сменяется основным. Ступенькой, а не плавной осью: оси вариативного шрифта
    # After Effects не анимирует, и плавного перехода в .jsx не собрать — превью
    # обязано ступенить так же, иначе разъедется с AE. Амплитуды тоже нет.
    "weight": {"dur": 0.3},
    # «Glitch RGB»: слово появляется ГЛИТЧЕМ — тем же, что у строк интро. Механизм
    # не второй: в .jsx вызывается та же функция introAnimFX (размытие, аниматор
    # текста с мерцанием букв, ключи прозрачности), а числа — ОДНИ на интро и на
    # субтитры: они объявлены ниже (SUB_GLITCH_*) и берутся оттуда же, откуда их
    # берёт INTRO_ANIMS в build.py. Амплитуды у пресета нет.
    "glitch": {"dur": 0.44},
}
# Числа глитча появления (секунды и проценты прозрачности) — ОДИН источник на интро и
# на субтитры: INTRO_ANIMS в build.py собирается из них, сюда же смотрит пресет
# `glitch`. Вторая копия разошлась бы с первой молча, а разъехавшийся глитч виден
# только рендером.
SUB_GLITCH_DUR = 0.44
# Сила Gaussian Blur на слое слова глитча (было 6.8, пользователь 2026-09-11: вдвое слабее)
SUB_GLITCH_BLUR = 3.4
# Ключи прозрачности: мерцание слова (доли длительности, проценты).
SUB_GLITCH_OP_KEYS = [
    [0.0, 0],
    [0.05, 100],
    [0.1, 100],
    [0.1417, 0],
    [0.1833, 93],
    [0.225, 0],
    [0.2667, 100],
]
# Ключи селектора текста: у аниматора интро так «раскрывается» доля букв.
SUB_GLITCH_END_KEYS = [
    [0.017, 100],
    [0.205, 5],
    [0.392, 100],
]
# Доля блюра от амплитуды — только у подъёма: слово проявляется из размытия на тех же
# ключах, что подъём и проявление. У роста блюра нет вовсе (ни ключа, ни эффекта в .jsx):
# одновременно вырастать и выезжать из размытия — уже другой пресет.
SUB_ANIM_BLUR_K = 0.5
# Пик роста у пресета масштаба, %: третий ключ появляется на 60 % длительности.
SUB_ANIM_POP_PEAK = 108.0
SUB_ANIM_POP_PEAK_AT = 0.6
# Смена начертания у пресета weight — на середине длительности: тонкое -> основное.
SUB_ANIM_WEIGHT_SWITCH_AT = 0.5
# Стартовая прозрачность пресета weight, %: проявление ЛЁГКОЕ — слово приходит чуть
# приглушённым, а не проявляется из нуля, как у остальных пресетов (из нуля оно
# выглядело бы обычным фейдом, и начертание в нём терялось бы).
SUB_ANIM_WEIGHT_OP = 35.0
# Доля открытия слова у пресета wipe, %: первый ключ — закрыто, последний — открыто
# целиком. Доля, а не пиксели: ширина слова в .jsx и в превью своя, а картинка одна.
SUB_ANIM_WIPE_CLOSED, SUB_ANIM_WIPE_OPEN = 0.0, 100.0


@dataclass(frozen=True)
class SubAnim:
    """Пресет появления базового слова, разрешённый под кадр ролика.

    ``name`` — имя пресета (`rise`/`pop`/`wipe`/`weight`), ``dur`` — длительность
    появления, с; ``rise`` и ``blur`` — движение снизу и размытие появления, px кадра;
    ``scale`` — стартовый масштаб роста, процент (100 = роста нет); ``op`` — стартовая
    прозрачность, процент (0 = слово проявляется из нуля, 100 = не проявляется вовсе);
    ``font`` — тонкое начертание пресета weight (PostScript-имя, пусто = его нет).
    Числа готовые: под них уже применён вид «size» стиля; план кладёт их в ключи,
    .jsx — в HL_W_* одной подстановкой. Какие из полей читает пресет — решает он сам:
    у `rise` это подъём и блюр, у `pop` — масштаб, у `wipe` — доля открытия, у `weight`
    — начертание и прозрачность, а остальные остаются нейтральными (0/100), иначе
    движения складывались бы друг с другом.
    """
    name: str
    dur: float
    rise: float
    blur: float
    scale: float
    op: float = 0.0
    font: str = ""
    # Ключи мерцания пресета glitch: доли его длительности и проценты прозрачности.
    # Лежат готовыми в плане — превью интерполирует ИХ (ipvGlitchOp), .jsx те же числа
    # ставит ключами внутри introAnimFX. Своей копии кривой глитча ни у кого нет.
    op_keys: tuple[tuple[float, float], ...] = ()


def sub_anim_preset(preset: Any, dur: Any = None, amt: Any = None,
                    font: Any = None) -> SubAnim | None:
    """Пресет стиля -> `SubAnim`, либо None: «none», пусто и незнакомое имя — без анимации.

    Незнакомое имя (стиль правят руками) не роняет сборку и НЕ подменяется дефолтным
    пресетом: слово просто появляется как раньше. Длительность и амплитуда берутся из
    пресета, если ключ стиля молчит (None) или ноль («как задумано пресетом»).
    `font` (поле стиля sub_anim_font) читает только пресет weight: у остальных
    начертание не меняется, и чужая ручка в них молчит.
    """
    name = str(preset or "").strip().lower()
    spec = SUB_ANIM_PRESETS.get(name)
    if spec is None:
        return None

    def _num(v: Any) -> float:
        try:
            return float(v) if v else 0.0
        except (TypeError, ValueError):
            return 0.0                      # мусор в стиле — как «не задано»

    d = _num(dur)
    _dur = d if d > 0 else spec["dur"]
    if name == "wipe":
        # Открытие слева направо: доля открытия 0 -> 100 %, а подъём, масштаб и блюр
        # нейтральны — слово именно ОТКРЫВАЕТСЯ, а не въезжает. Прозрачность тоже
        # нейтральна (100): гасить слово вместе с открытием — другой пресет, и вторая
        # анимация складывалась бы с первой.
        return SubAnim(name=name, dur=_dur, rise=0.0, blur=0.0, scale=100.0, op=100.0)
    if name == "weight":
        # Начертание сменяется ступенькой в середине dur, проявление — лёгкое
        # (SUB_ANIM_WEIGHT_OP). Тонкого шрифта не задали — ступеньки нет вовсе, и
        # пресет работает одной прозрачностью, как написано в подсказке ручки.
        return SubAnim(name=name, dur=_dur, rise=0.0, blur=0.0, scale=100.0,
                       op=SUB_ANIM_WEIGHT_OP, font=str(font or "").strip())
    if name == "glitch":
        # Глитч: числа — общие с интро (SUB_GLITCH_*), а длительность стиля тянет за
        # собой и ключи мерцания: они заданы ДОЛЯМИ длительности, и при своей dur
        # глитч обязан играть в том же ритме, а не в ритме 0.44 с.
        k = _dur / SUB_GLITCH_DUR if SUB_GLITCH_DUR > 0 else 1.0
        return SubAnim(
            name=name, dur=_dur, rise=0.0, blur=SUB_GLITCH_BLUR, scale=100.0,
            op_keys=tuple((round(kt * k, 4), float(kv)) for kt, kv in SUB_GLITCH_OP_KEYS))
    a = _num(amt)
    # Амплитуда у КАЖДОГО из оставшихся пресетов своя по смыслу: у rise это подъём
    # снизу в px, у pop — стартовый масштаб в процентах. Поэтому она одна на стиль:
    # переключил пресет — взял его собственное число, а не амплитуду соседа.
    amount = a if a > 0 else spec["amt"]
    if name == "pop":
        # Рост: масштаб и только он. Подъём и блюр нейтральны — с ними слово
        # одновременно уезжало бы снизу, а это уже другой пресет.
        return SubAnim(name=name, dur=_dur, rise=0.0, blur=0.0, scale=amount)
    # Подъём снизу: движение и размытие появления (доля амплитуды), масштаб нейтрален.
    return SubAnim(name=name, dur=_dur, rise=amount, blur=amount * SUB_ANIM_BLUR_K,
                   scale=100.0)


def _anim_entry(a: SubAnim, t0: float) -> dict[str, list[list[float]]]:
    """Ключи появления и амплитуды пресета на слово, начинающееся в ``t0``.

    Значения — в единицах свойств AE: ``op`` 0..100, ``sc`` — проценты, ``dy``/``bl`` —
    пиксели, ``wp`` — доля открытия слова, ``ft`` — ступенька начертания (1 = тонкое,
    0 = основное). Первый ключ t0 — слово ещё не видно, последний — пресет отыгран.
    """
    t1 = round(float(t0) + a.dur, 4)
    if a.name == "pop":
        # Рост: ключи ТОЛЬКО масштаба, положение и прозрачность — по краям, как у
        # остальных пресетов. Пик (108 %) стоит на 60 % длительности — как в каталоге.
        return {
            "op": [[t0, 0.0], [t1, 100.0]],
            "sc": [[t0, a.scale],
                   [round(t0 + a.dur * SUB_ANIM_POP_PEAK_AT, 4), SUB_ANIM_POP_PEAK],
                   [t1, 100.0]],
        }
    if a.name == "wipe":
        # Открытие: доля открытия 0 -> 100 %, прозрачность стоит на 100 оба ключа —
        # слово открывается шторкой, а не проявляется. Ключ один и тот же в плане
        # и в .jsx: AE играет открытие маской, а прозрачность у него нейтральна.
        return {
            "op": [[t0, SUB_ANIM_WIPE_OPEN], [t1, SUB_ANIM_WIPE_OPEN]],
            "wp": [[t0, SUB_ANIM_WIPE_CLOSED], [t1, SUB_ANIM_WIPE_OPEN]],
        }
    if a.name == "weight":
        # Ступенька начертания: 1 — тонкое (sub_anim_font) до середины dur, дальше 0 —
        # основное. Тонкого шрифта нет — ключа нет: ступенить нечего, и слово живёт
        # одной прозрачностью.
        out: dict[str, list[list[float]]] = {"op": [[t0, round(a.op, 2)], [t1, 100.0]]}
        if a.font:
            out["ft"] = [[t0, 1.0],
                         [round(t0 + a.dur * SUB_ANIM_WEIGHT_SWITCH_AT, 4), 0.0]]
        return out
    if a.name == "glitch":
        # Мерцание глитча: те же ключи прозрачности, что играет introAnimFX в .jsx, —
        # переведённые в АБСОЛЮТНОЕ время слова. Прозрачность здесь ступеньками
        # (в .jsx ключи линейные), поэтому превью интерполирует их линейно —
        # ipvGlitchOp, а не keysAt: у глитча кривая своя и общая с интро.
        return {"op": [[round(t0 + kt, 4), float(kv)] for kt, kv in a.op_keys]}
    return {
        "op": [[t0, 0.0], [t1, 100.0]],
        "dy": [[t0, round(a.rise, 2)], [t1, 0.0]],
        "bl": [[t0, round(a.blur, 2)], [t1, 0.0]],
    }


def sub_anim_keys(a: SubAnim, t0: float) -> dict[str, Any]:
    """План появления слова: ``{"name","dur", <свойство>: [[t, значение], …]}``.

    Единственный источник ключей появления базового слова: их читают предпросмотр
    (рисует спан слова на момент t интерполяцией ``keysAt``) и .jsx (ставит те же
    ключи на слой через ``subAnimKeys``). Ни одна из сторон кривых не считает.
    """
    out: dict[str, Any] = {"name": a.name, "dur": _r(a.dur, 4)}
    out.update(_anim_entry(a, float(t0)))
    return out


def _js_num(v: float) -> str:
    """Число подстановки .jsx: целые без хвоста (120, а не 120.0), дробные — как есть."""
    f = float(v)
    return str(int(f)) if f == int(f) else ("%g" % f)


def sub_anim_join_call(a: SubAnim) -> str:
    """Вызов появления для цикла слов СО СКЛЕЙКАМИ: там своё место вставки.

    Слово рисуется вторым проходом, уже после раскладки строк: позицию задаёт
    `finalY`, а стартовый масштаб роста едет полем 7 строки данных SUBS (``rsw[7]``).
    Поля нет (ролик собран пресетом без масштаба) — берётся HL_W_SC из объявления:
    число одно на сборку, второй копии нет.
    """
    return (" try{ subAnimKeys(L, t0, finalY, (rsw[7]==null ? HL_W_SC : rsw[7])); }catch(e){}")


def sub_anim_js(a: SubAnim | None) -> dict[str, str]:
    """Подстановки шаблона под появление БАЗОВЫХ слов (пресет sub_anim).

    Пустой пресет (`sub_anim="none"`, незнакомое имя) — все подстановки пусты:
    .jsx без ключа стиля собирается байт в байт как раньше (эталон golden_geometry.jsx).

    Пресет включён — подстановки такие:

    * ``decl`` — объявление чисел HL_W_DUR/HL_W_RISE/HL_W_BLUR/HL_W_SC
      (и HL_W_FONT, если у пресета есть тонкое начертание);
    * ``fn`` — ``subAnimKeys(L, t0, y, half)``: те же ключи, что лежат в плане, на слой
      слова. Позиция считается от АВТОРСКОЙ позиции слоя (её в этот момент уже поставил
      setValue), масштаб и прозрачность — от значений по умолчанию, поэтому второй
      вызов функции на том же слое ничего не портит. Куски, которых у пресета нет
      (масштаб роста, маска открытия, смена начертания, блюр), в текст НЕ попадают:
      мёртвая ветка в .jsx — подстановка, которая однажды разойдётся с планом;
    * ``call`` — вызов функции в ветке белого слова цикла «по слову» (место позиции
      там своё — центр кадра, потому и строка своя).

    Кривые ключей ставит easePair — тот же 35/90, что у жёлтых; крайние ключи
    остаются BEZIER, как у проявления жёлтого. Своей кривой у пресета нет: второй
    копии формулы в .jsx не заводится.
    """
    if a is None:
        return {"decl": "", "fn": "", "call": ""}
    decl = (
        "\n    // Появление базового слова (пресет sub_anim, стиль): те же ключи, что"
        "\n    // лежат в плане сцены, — числа считает Python (core/xml2ae/layout.py),"
        "\n    // .jsx их только ставит. Ни одной своей кривой здесь нет."
        "\n    // HL_W_SC — стартовый размер роста, процент (у остальных пресетов — 100: роста нет)."
        "\n    var HL_W_DUR = %s, HL_W_RISE = %s, HL_W_BLUR = %s, HL_W_SC = %s;"
        % (_js_num(a.dur), _js_num(a.rise), _js_num(a.blur), _js_num(a.scale)))
    if a.font:
        decl += ("\n    // HL_W_FONT — тонкое начертание пресета «начертание»: им слово"
                 "\n    // приходит, а в середине появления сменяется основным — ступенькой."
                 "\n    var HL_W_FONT = %s;" % _js(a.font))
    # Ключи масштаба — только у пресета роста: у остальных стартовый размер нейтрален
    # (100), и ключи 100 -> 108 -> 100 дали бы слову ЛИШНИЙ рост, которого нет ни в
    # плане, ни в превью. Пик и его доля длительности — из тех же констант, что
    # считают ключи плана.
    _peak = (
        "\n        var sc = tg.property(\"ADBE Scale\");"
        "\n        if (sc){"
        "\n            sc.setValueAtTime(t0, [half, half]);"
        "\n            sc.setValueAtTime(t0+HL_W_DUR*%(at)g, [%(pk)g, %(pk)g]);"
        "\n            sc.setValueAtTime(t0+HL_W_DUR, [100, 100]);"
        "\n            easePair(sc);"
        "\n        }"
        % {"at": SUB_ANIM_POP_PEAK_AT, "pk": SUB_ANIM_POP_PEAK}) if a.name == "pop" else ""
    # Открытие слова: маска-прямоугольник, у которой правый край едет от левого края
    # текста к правому, — ровно то, что делает clip-path: inset(0 X% 0 0) в превью.
    # Маска, а не эффект Linear Wipe: у маски и левая кромка, и правый край заданы явно
    # (в координатах текста), а у эффекта картинка зависит от угла и границ слоя —
    # проверить её без After Effects нечем. Левая кромка стоит на пиксель ЛЕВЕЕ текста:
    # прямоугольник нулевой ширины — вырожденный путь, а так открытая доля равна ровно
    # (правый край − левый край текста) / ширине текста.
    _wipe = (
        "\n        try{"
        "\n            var rr = L.sourceRectAtTime(t0+0.001, false);"
        "\n            if (rr && rr.width > 0){"
        "\n                var mk = L.property(\"ADBE Mask Parade\").addProperty(\"ADBE Mask Atom\");"
        "\n                try{ mk.maskMode = MaskMode.ADD; }catch(e){}"
        "\n                try{ mk.maskFeather = [0, 0]; }catch(e){}   // край жёсткий, как у clip-path"
        "\n                var mp = mk.property(\"ADBE Mask Shape\");"
        "\n                var wx = rr.left - 1, wt = rr.top, wb = rr.top + rr.height;"
        "\n                mp.setValueAtTime(t0, subWipeRect(wx, wt, rr.left, wb));"
        "\n                mp.setValueAtTime(t0+HL_W_DUR, subWipeRect(wx, wt, rr.left+rr.width, wb));"
        "\n                easePair(mp);   // та же кривая 35/90, что у ключей плана"
        "\n            }"
        "\n        }catch(e){ _LOG(\"открытие слова маской: \" + e); }"
        if a.name == "wipe" else "")
    # Прямоугольник маски открытия: вершины в ОДНОМ порядке у обоих ключей — иначе AE
    # морфит путь как попало, и слово открывается не слева направо.
    _wipe_fn = (
        "\n    // Прямоугольник маски открытия слова: (x1,y1) — левый верх, (x2,y2) — правый низ."
        "\n    function subWipeRect(x1, y1, x2, y2){"
        "\n        var s = new Shape();"
        "\n        s.vertices = [[x1,y1],[x2,y1],[x2,y2],[x1,y2]];"
        "\n        s.closed = true;"
        "\n        return s;"
        "\n    }" if a.name == "wipe" else "")
    # Смена начертания: Source Text — единственное свойство, которым в AE меняется шрифт
    # слоя. Ключи у него ДЕРЖАЩИЕ (HOLD): между тонким и основным документом
    # интерполяции нет, и шаг обязан быть ступенькой — как в превью и в ключах плана.
    # Оба документа снимаются с слоя ДО первой установки ключа: после неё `value` уже
    # отдаёт значение ключа, и «основное» начертание получилось бы тонким.
    _font = (
        "\n        try{"
        "\n            var td = L.property(\"ADBE Text Properties\").property(\"ADBE Text Document\");"
        "\n            if (td){"
        "\n                var db = td.value;   // документ слова: основное начертание"
        "\n                var dt = td.value;   // второй документ — тонкое"
        "\n                setFont(dt, HL_W_FONT);"
        "\n                td.setValueAtTime(t0, dt);"
        "\n                td.setValueAtTime(t0+HL_W_DUR*%(at)g, db);"
        "\n                for (var q=1; q<=td.numKeys; q++)"
        "\n                    td.setInterpolationTypeAtKey(q, KeyframeInterpolationType.HOLD,"
        "\n                                                 KeyframeInterpolationType.HOLD);"
        "\n            }"
        "\n        }catch(e){ _LOG(\"смена начертания слова: \" + e); }"
        % {"at": SUB_ANIM_WEIGHT_SWITCH_AT} if a.font else "")
    # Блюр — только у пресета с ненулевой амплитудой размытия (у подъёма снизу).
    _blur = (
        "\n        if (HL_W_BLUR > 0){"
        "\n            try{"
        "\n                var bl = L.property(\"ADBE Effect Parade\").addProperty(\"ADBE Gaussian Blur 2\");"
        "\n                bl.property(\"ADBE Gaussian Blur 2-0003\").setValue(0);   // Repeat Edge Pixels = 0"
        "\n                var bpv = bl.property(\"ADBE Gaussian Blur 2-0001\");"
        "\n                bpv.setValueAtTime(t0, HL_W_BLUR); bpv.setValueAtTime(t0+HL_W_DUR, 0);"
        "\n                easePair(bpv);"
        "\n            }catch(e){ _LOG(\"блюр появления слова: \" + e); }"
        "\n        }" if a.blur > 0 else "")
    # Подъём снизу — только у пресета с ненулевой амплитудой подъёма: у остальных
    # ключей Position нет вовсе (у маски, начертания и роста слово стоит на месте).
    _pos = (
        "\n        var p = tg.property(\"ADBE Position\");"
        "\n        if (p){"
        "\n            var base = p.value;"
        "\n            var X = (base && base.length > 1) ? base[0] : SW/2;"
        "\n            var by = (base && base.length > 1) ? base[1] : y;"
        "\n            if (HL_W_RISE){"
        "\n                p.setValueAtTime(t0, [X, by+HL_W_RISE]);"
        "\n                p.setValueAtTime(t0+HL_W_DUR, [X, by]);"
        "\n                easePair(p);"
        "\n            }"
        "\n        }" if a.rise > 0 else "")
    # Глитч — ЕДИНСТВЕННЫЙ пресет, у которого своя ветка: он не ставит ключи сам, а
    # зовёт ту же функцию, которой играет глитч интро (introAnimFX). Второго глитча в
    # сборке не заводится: размытие, аниматор текста с мерцанием букв и ключи
    # прозрачности — её код. y/half глитчу не нужны: слово не едет и не растёт.
    _glitch = (
        "\n        // Глитч появления — тот же механизм, что у строк интро (introAnimFX):"
        "\n        // размытие, аниматор текста с мерцанием букв и ключи прозрачности. Своих"
        "\n        // ключей здесь нет — иначе глитчей в сборке стало бы два."
        "\n        try{ introAnimFX(L, t0, \"glitch\", null, null, null, null, null, null); }"
        "\n        catch(e){ _LOG(\"глитч появления слова: \" + e); }"
        if a.name == "glitch" else "")
    _body = _glitch if a.name == "glitch" else (
        _pos +
        "\n        var op = tg.property(\"ADBE Opacity\");"
        "\n        if (op){ op.setValueAtTime(t0, %(op0)s); op.setValueAtTime(t0+HL_W_DUR, 100); easePair(op); }"
        % {"op0": _js_num(a.op)} + _peak + _wipe + _font + _blur)
    fn = (
        "\n    // Ключи появления базового слова: они РАЗНЫЕ у пресетов, и собирается ровно"
        "\n    // то, что нужно этому, — ни одной мёртвой ветки. Позиция берётся от УЖЕ"
        "\n    // поставленной позиции слоя: второй вызов на том же слое не сдвигает слово."
        "\n    function subAnimKeys(L, t0, y, half){"
        "\n        var tg = L.property(\"ADBE Transform Group\");"
        "\n        if (!tg) return;" + _body +
        "\n    }" + _wipe_fn)
    return {
        "decl": decl,
        "fn": fn,
        # Место вызова подстановка одна на оба цикла слов: цикл СО СКЛЕЙКАМИ
        # перебивает её своей строкой (там слово рисуется вторым проходом).
        "call": " try{ subAnimKeys(L, t0, POSY, HL_W_SC); }catch(e){}",
    }


# ---- Подложка слова (highlight / pill): ОДИН шейп-слой с ключами ------------------
# Каталог даёт два стиля: маркер за словом, «прокрашивающийся» при появлении
# (highlight), и скруглённая «таблетка», прыгающая от слова к слову (pill). В AE это
# одна и та же фигура — прямоугольник со скруглением ПОД текстом, — и различает их
# только то, что происходит на появлении слова: у маркера раскрывается ширина за
# sweep секунд, у таблетки ширина уже целая. Поэтому и механизм один: шейп-слой
# создаётся РОВНО ОДИН на сборку (в прекомпе субтитров, под словами), а ключи на нём
# ставятся по таймингам слов.
#
# Почему не слой на каждое слово: в трёхминутном ролике сотни слов, и сотни
# шейп-слоёв — это и вес проекта, и время сборки, и таймлайн, в котором ничего не
# найти. Один слой с ключами Position (HOLD: фигура именно ПРЫГАЕТ на слово) и
# Rect Size (у маркера растёт кривой easePair) даёт ту же картинку при одном слое.
#
# Почему не режим плашки sub_bg_*: плашка под строкой — ОДИН прямоугольник на всю
# строку, её ширина считается ВЫРАЖЕНИЕМ от sourceRectAtTime слоя субтитров, и стоит
# она на месте весь ролик. Подложка слова живёт по таймингам ПРОИЗНОСИМЫХ слов: в
# строке из четырёх слов она перескакивает четыре раза. Общего у них — только
# «фигура под текстом», поэтому у подложки своя группа настроек (sub_wbg_*), а не
# галка плашки: свести их в одну ручку значило бы сломать уже собранные ролики.
SUB_WBG_KINDS = ("highlight", "pill")
# Момент, с которого фигура считается «за текущим словом», и её конец считает Python
# (plan_subs): у слова в режиме строк это время произнесения, зажатое в окно строки,
# а не момент появления слоя. Второй копии правила «когда слово звучит» нет.


@dataclass(frozen=True)
class SubWBG:
    """Подложка слова, разрешённая под кадр ролика.

    ``kind`` — `highlight` (маркер раскрывается за ``sweep``) или `pill` (таблетка
    появляется целиком); ``fill``/``op`` — цвет и прозрачность фигуры; ``h``,
    ``round``, ``pad`` — высота, скругление и поле по бокам, px кадра; ``dy`` —
    доводка по вертикали. Числа готовые: вид «size»/«y» стиля к ним уже применён
    (``plan_style.read_style``), второй раз не множим.
    """
    kind: str
    fill: list[Any]
    op: float
    h: float
    round: float
    pad: float
    dy: float
    sweep: float


def sub_wbg(style: Any) -> SubWBG | None:
    """Подложка слова из стиля: None — выключена галкой, иначе готовые числа.

    Галка читается СЫРОЙ (как ``sub_bg``): «не задано» и ноль значат выключено.
    Незнакомый вид фигуры (стиль правят руками) не роняет сборку — берётся маркер:
    подложка включена, и нарисовать надо хоть что-то.
    """
    if not _num(style.sub_wbg_on):
        return None
    kind = str(style.sub_wbg_kind or "").strip().lower()
    if kind not in SUB_WBG_KINDS:
        kind = SUB_WBG_KINDS[0]
    sweep = max(0.0, _num(style.sub_wbg_sweep))
    return SubWBG(
        kind=kind,
        fill=list(style.sub_wbg_fill or []),
        op=_num(style.sub_wbg_op),
        h=_num(style.sub_wbg_h),
        round=_num(style.sub_wbg_round),
        pad=_num(style.sub_wbg_pad),
        dy=_num(style.sub_wbg_dy),
        # У таблетки раскрытия нет вовсе: ширина целая с первого кадра.
        sweep=(sweep if kind == "highlight" else 0.0),
    )


def _num(v: Any) -> float:
    """Число стиля безопасно: пусто, мусор и None — ноль (стиль правят руками)."""
    try:
        return float(v) if v else 0.0
    except (TypeError, ValueError):
        return 0.0


def sub_wbg_plan(w: SubWBG) -> dict[str, Any]:
    """Числа подложки для превью: ровно то, что читает ipvSubs, — своих у него нет."""
    return {"kind": w.kind, "fill": list(w.fill), "op": w.op, "h": w.h,
            "round": w.round, "pad": w.pad, "dy": w.dy, "sweep": w.sweep}


def sub_wbg_moment(w_s: float, r_s: float | None = None,
                   r_e: float | None = None) -> float:
    """Момент, с которого слово считается ТЕКУЩИМ (за ним встаёт подложка).

    В режиме «по слову» это время произнесения слова (слово там и есть своя реплика).
    В режиме строк слово стоит в строке с её начала, а звучит позже: момент — время
    слова, ЗАЖАТОЕ в окно строки (не раньше её начала и не позже конца), как у
    появления жёлтого в строке. Считает Python: превью и .jsx берут готовое число,
    своей копии правила «когда слово звучит» ни у кого нет.
    """
    t = float(w_s)
    if r_e is not None:
        t = min(max(t, float(r_s or 0.0)), float(r_e))
    return round(t, 4)


def sub_wbg_js(w: SubWBG) -> dict[str, str]:
    """Подстановки .jsx под подложку слова: слой, ключи на слово и хвост сборки.

    * ``js`` — создание ОДНОГО шейп-слоя в прекомпе субтитров (до цикла слов, значит
      под ними) и функция ``wbgKeys``: она берёт размер слова у самого слоя
      (``sourceRectAtTime``) и ставит ключи. Момент и конец слова ей передаёт цикл —
      их посчитал Python, в .jsx своей формулы «когда слово звучит» нет;
    * ``tail`` — после цикла: окна показа подложки применяются разом (HOLD), кривые
      и точка входа слоя;
    * ``call_*`` — вызовы из циклов слов: у каждого цикла своё имя переменной строки
      данных, поэтому и строка своя (как у появления базового слова).

    Размер и позиция считаются от ПРЯМОУГОЛЬНИКА СЛОВА, а не от числа в плане:
    ширину слова знает только сам AE (метрики шрифта его), и в превью она тоже
    своя — общая у них доля раскрытия по ключам плана, как у маски открытия.
    """
    h = "%g" % w.h
    pad = "%g" % w.pad
    dy = "%g" % w.dy
    op = "%g" % w.op
    js = (
        "\n    // ---- подложка слова (стиль sub_wbg): ОДИН шейп-слой с ключами ----\n"
        "    // Слой создаётся ДО цикла слов: новые слои встают наверх, значит фигура\n"
        "    // окажется ПОД словами. Ключи ставит wbgKeys из цикла — по одному слову.\n"
        "    var wbgLayer = subc.layers.addShape();\n"
        '    wbgLayer.name = "Подложка слова";\n'
        '    var wbgC = wbgLayer.property("ADBE Root Vectors Group");\n'
        '    var wbgR = wbgC.addProperty("ADBE Vector Shape - Rect");\n'
        '    wbgR.property("ADBE Vector Rect Roundness").setValue(%g);\n'
        '    var wbgSz = wbgR.property("ADBE Vector Rect Size");\n'
        '    var wbgFi = wbgC.addProperty("ADBE Vector Graphic - Fill");\n'
        '    wbgFi.property("ADBE Vector Fill Color").setValue(%s);\n'
        '    var wbgP = wbgLayer.property("ADBE Transform Group").property("ADBE Position");\n'
        '    var wbgO = wbgLayer.property("ADBE Transform Group").property("ADBE Opacity");\n'
        "    var WBG_W = [];   // окна показа: [время, прозрачность] — применяются после цикла\n"
        "    function wbgKeys(L, tM, outT, cx, cy){\n"
        "        try{\n"
        "            var rr = L.sourceRectAtTime(tM+0.001, false);\n"
        "            if (rr && rr.width > 0){\n"
        "                var w = rr.width + 2*%s, hh = %s;\n"
        "                // Слово в AE стоит базовой линией в (cx, cy): центр его прямоугольника —\n"
        "                // от неё, поэтому вертикаль берём у самого текста, а не из кегля.\n"
        "                var mx = cx + rr.left + rr.width/2;\n"
        "                var my = cy + rr.top + rr.height/2 + %s;\n"
        "                wbgP.setValueAtTime(tM, [mx, my]);\n"
        % (w.round, _fill_js(w.fill), pad, h, dy)
    ) + (
        # Маркер: ширина раскрывается от центра слова за sweep. Раскрытие от центра, а не
        # от левого края: и Position, и Rect Size пришлось бы вести парой ключей на каждое
        # слово, и вставка ключа в середину чужого окна (слова идут внахлёст) сдвигала бы
        # индексы соседей. Одним свойством картинка та же — фигура «прокрашивается» под словом.
        "                wbgSz.setValueAtTime(tM, [1, hh]);\n"
        "                wbgSz.setValueAtTime(tM+%g, [w, hh]);\n" % w.sweep if w.sweep > 0 else
        # Таблетка: ширина целая сразу — она не раскрывается, а прыгает.
        "                wbgSz.setValueAtTime(tM, [w, hh]);\n"
    ) + (
        "                WBG_W.push([tM, %s]); WBG_W.push([outT, 0]);\n"
        "            }\n"
        '        }catch(e){ _LOG("подложка слова: " + e); }\n'
        "    }" % op
    )
    # Хвост: окна показа и кривые. Позиция всегда HOLD — фигура прыгает; ширина у маркера
    # идёт кривой easePair (та же 35/90, что у остальных ключей), но МЕЖДУ словами стоит
    # на месте (HOLD у «конца раскрытия»): иначе она ужималась бы к следующему слову ещё
    # до его появления. У таблетки HOLD у всех ключей ширины — она прыгает целиком.
    _size_types = (
        "        // Ключи ширины идут парами (раскрытие: 1 px -> полная ширина) — кривая\n"
        "        // у первого ключа пары, HOLD у второго (между словами ширина стоит).\n"
        "        for (var ws=1; ws<=wbgSz.numKeys; ws++)\n"
        "            wbgSz.setInterpolationTypeAtKey(ws,"
        " (ws%2)?KeyframeInterpolationType.BEZIER:KeyframeInterpolationType.HOLD,"
        " (ws%2)?KeyframeInterpolationType.BEZIER:KeyframeInterpolationType.HOLD);\n"
        if w.sweep > 0 else
        "        // Таблетка: ширина меняется СТУПЕНЬКОЙ — она прыгает на слово целиком.\n"
        "        for (var ws=1; ws<=wbgSz.numKeys; ws++)\n"
        "            wbgSz.setInterpolationTypeAtKey(ws, KeyframeInterpolationType.HOLD,"
        " KeyframeInterpolationType.HOLD);\n"
    )
    tail = (
        "\n    // ---- подложка слова: окна показа и кривые (после цикла слов) ----\n"
        "    if (WBG_W.length){\n"
        "        WBG_W.sort(function(a,b){ return a[0]-b[0]; });\n"
        "        for (var wk=0; wk<WBG_W.length; wk++) wbgO.setValueAtTime(WBG_W[wk][0], WBG_W[wk][1]);\n"
        "        // Показ — HOLD: между словами подложки нет (в зазоре строк она не висит).\n"
        "        for (var wo=1; wo<=wbgO.numKeys; wo++)\n"
        "            wbgO.setInterpolationTypeAtKey(wo, KeyframeInterpolationType.HOLD,"
        " KeyframeInterpolationType.HOLD);\n"
        "        temporalEase(wbgSz, HL_EASE_IN, HL_EASE_OUT);\n"
        + _size_types +
        "        for (var wp=1; wp<=wbgP.numKeys; wp++)\n"
        "            wbgP.setInterpolationTypeAtKey(wp, KeyframeInterpolationType.HOLD,"
        " KeyframeInterpolationType.HOLD);\n"
        "        wbgLayer.inPoint = WBG_W[0][0];\n"
        "        wbgLayer.outPoint = WBG_W[WBG_W.length-1][0];\n"
        "    }"
    )
    # Вызовы из циклов: (момент, конец, X слоя, Y слоя). В режиме строк момент — из данных
    # слова (поле 4): там слово стоит в строке с её начала, а звучит позже.
    return {
        "js": js, "tail": tail,
        "call_base": " try{ wbgKeys(L, t0, sw[1]/FPS, SW/2, POSY); }catch(e){}",
        "call_hl": " try{ wbgKeys(L, t0, sw[5]/FPS, SW/2, finalY); }catch(e){}",
        "call_hl_joined": " try{ wbgKeys(L, t0, rsw[5]/FPS, wCenter, finalY); }catch(e){}",
        "call_row": (" try{ wbgKeys(L, (r_words[wi][4]!=null?r_words[wi][4]:r_t0s[wi]),"
                     " r_t1, wCenter, lineY); }catch(e){}"),
    }


# ---- Заливка текста градиентом и свечение: эффекты на слоях слов ------------------
# Оба — класс Б каталога: в AE это эффект на слое слова (ключей у них нет, числа
# ставит Python), в превью — CSS на том же слове. Живут они в ОДНОЙ функции на всю
# сборку (subGrad/subGlow), а не строкой в каждом из четырёх циклов субтитров: циклов
# четыре, и копия строки в каждом разошлась бы с остальными молча.
def sub_fill_js(style: Any) -> str:
    """Заливка текста градиентом (``sub_fill_mode="gradient"``) — подстановка .jsx.

    Пустая при сплошной заливке: .jsx со стилем по умолчанию остаётся прежним байт
    в байт. Градиент ставится эффектом Gradient Ramp (``ADBE Ramp``) на слой слова:
    своим эффектом его не сделать — стопы градиента ШЕЙП-слоя из ExtendScript не
    пишутся вовсе (на этом уже обожглись на верхней строке-прогрессе, там солид +
    Ramp + маска). Точки рампы считаются по прямоугольнику СЛОВА той же формулой
    линии градиента, что в CSS (``background-clip:text``): длина = |W·sin| + |H·cos|
    от угла, центр прямоугольника. Своей формулы у превью нет — там градиент рисует
    сам CSS по тем же двум цветам и углу.
    """
    if str(style.sub_fill_mode or "").strip().lower() != "gradient":
        return ""
    ang = _num(style.sub_grad_angle)
    return (
        "\n    // ---- заливка текста градиентом (стиль sub_fill_mode) ----\n"
        "    // Угол — как в CSS: 0 вверх, 90 вправо (по часовой). Длину линии градиента\n"
        "    // и её центр считаем по прямоугольнику слова тем же правилом, что CSS.\n"
        "    var GRAD_FROM = %s, GRAD_TO = %s, GRAD_ANG = %g;\n"
        "    function subGrad(L, t0){\n"
        "        try{\n"
        "            var rr = L.sourceRectAtTime(t0+0.001, false);\n"
        "            if (rr && rr.width > 0){\n"
        "                var gw = rr.width, gh = (rr.height > 0 ? rr.height : 1);\n"
        "                var ga = GRAD_ANG*Math.PI/180;\n"
        "                var gdx = Math.sin(ga), gdy = -Math.cos(ga);\n"
        "                var glen = Math.abs(gw*gdx) + Math.abs(gh*gdy);\n"
        "                var gcx = rr.left + gw/2, gcy = rr.top + gh/2;\n"
        "                var gRamp = L.property(\"ADBE Effect Parade\").addProperty(\"ADBE Ramp\");\n"
        "                gRamp.property(\"ADBE Ramp-0001\").setValue([gcx-gdx*glen/2, gcy-gdy*glen/2]);\n"
        "                gRamp.property(\"ADBE Ramp-0002\").setValue(GRAD_FROM);\n"
        "                gRamp.property(\"ADBE Ramp-0003\").setValue([gcx+gdx*glen/2, gcy+gdy*glen/2]);\n"
        "                gRamp.property(\"ADBE Ramp-0004\").setValue(GRAD_TO);\n"
        "                gRamp.property(\"ADBE Ramp-0007\").setValue(0);   // Blend With Original = 0\n"
        "            }\n"
        '        }catch(e){ _LOG("градиент текста: " + e); }\n'
        "    }"
        % (_fill_js(style.sub_grad_from), _fill_js(style.sub_grad_to), ang)
    )


def sub_fill_call(style: Any, t_expr: str = "t0") -> str:
    """Вызов градиента в цикле слов; пусто при сплошной заливке (golden).

    ``t_expr`` — выражение времени слова в ЭТОМ цикле: прямоугольник берётся у слоя на
    момент, когда слово уже нарисовано своим текстом (у слова-счётчика текст ключевой,
    и на нулевом кадре он другой).
    """
    if str(style.sub_fill_mode or "").strip().lower() != "gradient":
        return ""
    return " subGrad(L, %s);" % t_expr


# Порог свечения — как у слов интро (intro_word_glow_thr): выше порога буква светится,
# ниже — нет. Число одно на подложку и на превью: второй копии нет.
SUB_GLOW_THR = 149
# «Glow Colors» эффекта Glo2: 2 = A & B Colors. Тогда цвет свечения берётся из
# Color A/Color B, а не из цвета буквы, — им и красим (matchName, а не имя свойства:
# имена в локализованном AE свои).
GLOW_COLORS_AB = 2


def sub_glow_js(style: Any) -> str:
    """Свечение текста (``sub_glow_on``) — эффект Glo2 на слоях слов; пусто при выключенном.

    Числа — те же, что у интро (``ADBE Glo2``: порог/радиус/интенсивность), плюс цвет:
    Glo2 светит ЦВЕТОМ БУКВЫ, если не переключить «Glow Colors» на A & B, поэтому
    цвет из стиля ставится в Color A и Color B. Галка «только жёлтые» превращает
    эффект в ветку по признаку слова — как у интро (``introHlGlow`` светит только
    жёлтым хайлайта).
    """
    if not _num(style.sub_glow_on):
        return ""
    only_yellow = "true" if bool(style.sub_glow_yellow) else "false"
    return (
        "\n    // ---- свечение текста (стиль sub_glow): Glo2 на слое слова, как у интро ----\n"
        "    var GLOW_RAD = %g, GLOW_INT = %g, GLOW_FILL = %s, GLOW_YEL = %s;\n"
        "    function subGlow(L, hl){\n"
        "        if (GLOW_YEL && !hl) return;   // «только жёлтые»: белым свечения нет\n"
        "        try{\n"
        "            if (GLOW_INT <= 0) return;\n"
        "            var gGl = L.property(\"ADBE Effect Parade\").addProperty(\"ADBE Glo2\");\n"
        "            if (!gGl) return;\n"
        "            gGl.property(\"ADBE Glo2-0002\").setValue(%d);   // Glow Threshold\n"
        "            gGl.property(\"ADBE Glo2-0003\").setValue(GLOW_RAD);\n"
        "            gGl.property(\"ADBE Glo2-0004\").setValue(GLOW_INT);\n"
        "            try{ gGl.property(\"ADBE Glo2-0007\").setValue(%d); }catch(e){}   // Glow Colors: A & B\n"
        "            try{ gGl.property(\"ADBE Glo2-0012\").setValue(GLOW_FILL); }catch(e){}   // Color A\n"
        "            try{ gGl.property(\"ADBE Glo2-0013\").setValue(GLOW_FILL); }catch(e){}   // Color B\n"
        '        }catch(e){ _LOG("свечение слова: " + e); }\n'
        "    }"
        % (_num(style.sub_glow_rad), _num(style.sub_glow_amt), _fill_js(style.sub_glow_fill),
           only_yellow, SUB_GLOW_THR, GLOW_COLORS_AB)
    )


def sub_glow_call(style: Any, flag: str = "hl") -> str:
    """Вызов свечения в цикле слов: вторым аргументом — признак «слово жёлтое».

    Признак у каждого цикла свой (``hl``, ``w_hl``), поэтому имя признака приходит
    параметром: своей копии решения «жёлтое ли слово» в шаблоне не заводится.
    """
    if not _num(style.sub_glow_on):
        return ""
    return " subGlow(L, %s);" % flag


# Базовая позиция интро: превью ставит блок по plan.intro[i].y, шаблон
# берёт готовое iDy — позиция живёт в Python, вторая копия не заводится. Числа — из
# AE_FULL: iDy=0, iTop=H/2 - 520.7894 - (nL/2)*LINE_STEP*(iSc/100); if(iTop<SAFE_TOP)
# iDy=SAFE_TOP-iTop. iSc — базовый масштаб прекомпа 96.8 × gs/100.
INTRO_BASE_Y = 520.7894     # база позиции прекомпа интро, px (подъём от центра кадра)
INTRO_LINE_STEP = 160.0     # шаг строки внутри прекомпа, px (= 100% ключа intro_line_step)
INTRO_SAFE_TOP = 285.0      # верх блока не выше этой линии кадра — иначе опускаем
INTRO_SCALE = 96.8          # базовый масштаб прекомпа при gs=100, %%
# Запасная доля ширины кадра для автофита интро: ею пользуются только прямые вызовы
# `_intro_fit_ds` без стиля (долю не передали). В сборке долю задаёт ручка СВОЕЙ камеры
# («Отступ от краёв», intro_margin/intro_margin2, доля = 1 − 2·margin/100) — одна на
# привязанное интро (только ужатие) и откреплённое (в обе стороны). Раньше константа была
# общим правилом для привязанного интро и жила в шаблоне (var INTRO_FIT_W), где считала
# от ширины прекомпа; с переездом автофита в scene_plan источник один — здесь.
INTRO_FIT_W = 0.92
# Затемнение под интро: числа сняты с amdi1.aep — пользователь в КАЖДОМ из
# четырёх роликов руками клал `Shape Layer 1` (мягкое чёрное затемнение снизу кадра, чтобы
# белый текст интро читался на светлой одежде). У всех четырёх одинаковы: прямоугольник
# 1416×1052, смещение прямоугольника внутри группы (−20, 610), чёрная заливка, обводки нет,
# Box Blur с радиусом 653. Разное — позиция слоя (−6…0, 441…606) и масштаб 87…103 %; здесь
# средние: SHADE_X = −4, SHADE_SCALE = 94. Позиция следовала за высотой интро (в среднем
# «y = INTRO_Y − 215», INTRO_Y — стиль intro_y), отсюда SHADE_DY. Слой висит на нуле
# «Камера 1» — координаты те же, что у нула «интро» (см. intro_y/intro_plan).
# Пиксели сняты с композиций шириной 1080 и множатся на ТО ЖЕ правило, что у карточки
# вставки — `_px_k` (min(W, H)/1080). Раньше здесь стояло своё `k = W / 1080`: в 16:9
# (1920×1080) оно давало 1.78 при короткой стороне 1080, то есть затемнение росло, хотя
# текст интро — нет (вид «size» у стиля от кадра не меняется). Правило одно на всю
# раскладку: и карточка, и затемнение растут вместе с короткой стороной кадра.
SHADE_W, SHADE_H = 1416, 1052       # размер прямоугольника, px кадра 1080
SHADE_OX, SHADE_OY = -20, 610       # смещение прямоугольника внутри группы, px
SHADE_BLUR = 653                    # радиус Box Blur, px
SHADE_X = -4                        # позиция слоя по X, px (среднее по роликам)
SHADE_DY = -215                     # позиция слоя: y = intro_y + SHADE_DY, px
SHADE_SCALE = 94                    # масштаб слоя, % (среднее по роликам) — процент, не px


def _intro_i_dy(h: float, n_lines: int, gs: float | None, step_k: float = 1.0) -> float:
    """Опускание блока интро под INTRO_SAFE_TOP, px. Масштаб группы
    (96.8·gs/100) выбирает вызывающий: у ПРИВЯЗАННОГО интро это НЕужатый gs (граница
    — там автофит режет только Scale, и опускание от него не зависит), у
    ОТКРЕПЛЁННОГО — фактический ds, который автофит мог и увеличить:
    растянутое по ширине кадра интро обязано опуститься под SAFE_TOP, иначе вылезет
    за верх кадра. Точность как в старом
    шаблоне: без округления, чтобы .jsx не поехал на сотых.

    step_k — множитель межстрочного интервала (intro_line_step/100): высота
    блока растёт вместе с шагом, поэтому под SAFE_TOP его опускают по ТОМУ ЖЕ шагу, что
    стоит в раскладке строк. При 1.0 числа прежние."""
    i_sc = INTRO_SCALE * (float(gs) if gs else 100.0) / 100.0
    i_top = h / 2 - INTRO_BASE_Y - (n_lines / 2.0) * (INTRO_LINE_STEP * step_k) * (i_sc / 100.0)
    if i_top < INTRO_SAFE_TOP:
        return INTRO_SAFE_TOP - i_top
    return 0.0


def _cap(ps: str | None, size: float) -> float:
    """Высота заглавных (капитель) строки, px: верх «H» из контуров глифа —
    у заглавной нет ни хвоста, ни выносов, поэтому её верх и есть верх строки. Шрифта,
    файла или глифа нет — 0.72 кегля (та же запасная ветка, что была у чернил: раскладка
    обязана строиться и без файла шрифта). Вторая копия формулы не заводится — сюда
    смотрит и вертикаль большой строки, и верх блока."""
    ext = _fonts.ink_extent(ps, "H", size)
    if ext is None:
        return 0.72 * size
    return float(ext[0])


# Высота большого слова, % от высоты стопки (доработка ZY-2): дефолт ручки
# intro_big_over из styles.BASE. Сборка всегда передаёт число из стиля — здесь оно для
# прямых вызовов раскладки; совпадение с дефолтом ручки стережёт тест (test_intro_big.py),
# чтобы второе число не разъехалось с первым молча.
INTRO_BIG_OVER = 110.0


def intro_big_layout(lines: list[dict[str, Any]], ys_stack: Sequence[float], fsize: float, fonts: Sequence[str | None], back_scale: float, gap: float,
                     over: float = INTRO_BIG_OVER) -> tuple[list[float | None], list[float | None], list[float | None]]:
    """Раскладка «большое слева»: ПЕРВАЯ строка группы с флагом big встаёт
    слева крупно, остальные строки группы — стопкой справа от неё, выровненные по левому
    краю. Возвращает (lx, lk, ys) — три списка ТОЙ ЖЕ длины, что lines:

    * ys — Y базовых линий в координатах прекомпа, по строке на элемент (большая строка
      садится на БАЗОВУЮ линию последней строки стопки, строки стопки — готовые из ys_stack);
    * lk — множитель кегля строки: у большой S/fsize, у строк стопки None;
    * lx — левый край строки, px прекомпа ОТ ЦЕНТРА: у всех строк группы с большой
      (и у большой, и у стопки — блок общий), у строк группы без большой None.

    Вертикаль — типографская, по ЗАГЛАВНЫМ и базовой линии (правка ZY), а не по чернилам:
    верх блока = y_first − cap(ps_first, size_first), низ = y_last — БАЗОВАЯ линия
    последней строки стопки. Кегль большой подобран под эту высоту с ручкой
    intro_big_over (доработка ZY-2): lk = over/100 · (y_last − верх)/cap(ps_big, fsize),
    и стоит она на той же базовой линии: y_big = y_last. При over=100 верх капители
    большой ровно совпадает с верхом блока, при дефолтных 110 — на 10 % выше стопки, как
    у эталона владельца. Чернила большой строки (asc/desc) в вертикали больше не
    участвуют: раньше низом считался низ ЧЕРНИЛ стопки, и хвост «Ц» в «ЗА МЕСЯЦ» (на
    7 px ниже базовой линии) утаскивал «8» вниз, а кратка «Й»/«Ё» так же портила верх.
    Кегль строки заднего плана — fsize·back_scale, как и прежде.

    Ширины — core.fonts.text_width (большая при S, стопка — каждая своим кеглем), блок
    центрирован: total = bigW + gap + max(stackW), lx_big = −total/2,
    lx стопки = −total/2 + bigW + gap.

    lines — строки группы ровно как уезжают в .jsx (поле big только у большой),
    ys_stack — Y базовых линий строк СТОПКИ (все, кроме большой: большая шаг не занимает,
    len(lines) − 1 значений). over — высота большого слова в % от высоты стопки (ручка
    intro_big_over, доработка ZY-2); дефолт INTRO_BIG_OVER держится равным
    styles.BASE["intro_big_over"] сторожем в тестах, сборка всегда передаёт число из стиля.
    Шрифт/глиф не найден (ink_extent/text_width дали None) —
    капитель 0.72 кегля, ширина 0.55 кегля на знак: раскладка строится и без файла шрифта
    (как автофит поступает с неизвестной шириной). Группа из одной строки большой не
    считается — флаг без эффекта, как и остальные big строки группы.
    """
    n = len(lines)
    if n <= 0:
        return [], [], []
    big_i = None
    for k in range(n):
        if lines[k].get("big"):
            big_i = k
            break
    if big_i is None or n < 2 or len(ys_stack) != n - 1:
        # Группа без большой строки (или раскладывать не с чем): флага нет ни у кого —
        # lx/lk пустые, ys отдаём как пришли (стопка целиком совпадает с lines).
        return ([None] * n, [None] * n,
                [round(float(y), 2) for y in ys_stack] if len(ys_stack) == n else [None] * n)

    def _text(i: int) -> str:
        return " ".join(str(w) for w in (lines[i].get("words") or []))

    def _size(i: int) -> float:
        """Кегль строки: задний план мельче, большая считается при fsize (её lk
        подбирается отдельно) — как в шаблоне, где back-скейл применяется к слою."""
        return fsize * back_scale if lines[i].get("back") else fsize

    def _width(i: int, size: float) -> float:
        wpx = _fonts.text_width(fonts[i], _text(i), size)
        if wpx is None:
            return 0.55 * size * len(_text(i))
        return float(wpx)

    stack_idx = [k for k in range(n) if k != big_i]
    y_first, y_last = float(ys_stack[0]), float(ys_stack[-1])
    # Верх блока — по капители ПЕРВОЙ строки стопки, низ — базовая линия ПОСЛЕДНЕЙ
    # Чернила тут не годятся: хвост «Ц» в «ЗА МЕСЯЦ» на 7 px ниже базовой
    # линии, и большая строка, выровненная по низу чернил, висела ниже строки.
    top = y_first - _cap(fonts[stack_idx[0]], _size(stack_idx[0]))
    cap_big = _cap(fonts[big_i], fsize)
    box_h = y_last - top
    # Кегль большой — от высоты стопки и ручки «Большое выше стопки» (доработка ZY-2):
    # over=100 — верх капители большой в верх блока, 110 (дефолт) — на десятую выше.
    lk = (float(over) / 100.0 * box_h / cap_big) if (box_h > 0 and cap_big > 0) else 1.0
    y_big = y_last                                  # та же базовая линия, что у стопки
    big_w = _width(big_i, fsize * lk)
    stack_w = [_width(k, _size(k)) for k in stack_idx]
    total = big_w + gap + (max(stack_w) if stack_w else 0.0)
    lx_big = -total / 2.0
    lx_stack = -total / 2.0 + big_w + gap

    lx: list[float | None]
    lks: list[float | None]
    ys: list[float | None]
    lx, lks, ys = [None] * n, [None] * n, [None] * n
    lx[big_i], lks[big_i], ys[big_i] = lx_big, lk, y_big
    for j, k in enumerate(stack_idx):
        lx[k], lks[k], ys[k] = lx_stack, None, float(ys_stack[j])
    # Округление как у intro_line_ys: сотые — столько же знаков, сколько у остальных
    # чисел .jsx; lk — четыре знака (масштаб слоя в .jsx всё равно печатается десятыми
    # процента, k*100).
    return ([None if v is None else round(v, 2) for v in lx],
            [None if v is None else round(v, 4) for v in lks],
            [None if v is None else round(v, 2) for v in ys])


def intro_line_ys(lines: list[dict[str, Any]], back_step: float, any_back_in_clip: bool = True, anchor: str = "center",
                  h: float = 1920.0, step_k: float = 1.0, back_step_after: float | None = None) -> list[float]:
    """Y базовых линий строк интро в координатах прекомпа (высота h), по числу строк.

    Шаг ДО строки заднего плана и шаг МЕЖДУ строками заднего плана — line_step *
    back_step, шаг ПОСЛЕ блока заднего плана к обычной строке — line_step *
    back_step_after, где line_step = INTRO_LINE_STEP * step_k.
    Минимума по чернилам (fonts.ink_extent) и зазора back_gap здесь больше нет: минимум (73.5 px на дефолтном шрифте) перекрывал шаг на малых back_step, и
    ручка «не меняла ничего», а жёсткие 0.75 после строки заднего плана вообще не
    читались из стиля. Высоту букв из файла шрифта теперь не спрашивают вовсе — шаг
    целиком задаёт ручка.

    lines — строки группы ровно как уезжают в .jsx (поле back только у настоящей строки
    заднего плана: акцент его перебивает), back_step — шаг строк заднего плана долей от
    обычного шага, back_step_after — шаг от заднего плана к обычной строке под ним;
    None (ключа нет в стиле) — прежнее поведение: берётся back_step этого же стиля,
    старые стили выглядят как раньше байт в байт.

    any_back_in_clip: в ролике есть строки заднего плана. Нет их — все шаги LINE_STEP и
    базовая линия по центру: ветка шаблона без back другой раскладки не знает, шаг по
    back_step там смысла не имеет.

    anchor: "first" — первая строка стоит в h/2, добавленная строка опускает только
    нижние (блок не поднимается); "center" — как раньше: без back h/2 - (nL-1)/2*LINE_STEP,
    с back и головой не back — h/2 - (nL-1)*60*k, иначе h/2 - totH/2. Округление до сотых:
    столько же знаков, сколько у остальных чисел .jsx.

    step_k — множитель межстрочного интервала (intro_line_step/100): ОДИН на
    весь шаг строки — базовые 160 px, «60» центровки с back и шаг заднего плана.
    При 1.0 числа прежние байт в байт (golden).
    """
    n = len(lines)
    if n <= 0:
        return []
    line_step = INTRO_LINE_STEP * step_k

    def _back(i: int) -> bool:
        return bool(lines[i].get("back"))

    steps = []
    for i in range(1, n):
        if not any_back_in_clip:
            steps.append(line_step)
            continue
        if _back(i) or _back(i - 1):
            # Шаг ПОСЛЕ блока заднего плана — своя ручка: видимые зазоры над
            # маленькой строкой и под ней разные (у владельца 53 и 23 px), а выровнять их
            # одним числом нельзя — высота букв и хвосты зависят от слов. Шаг ДО строки
            # заднего плана и между строками заднего плана остаётся общим back_step.
            step_frac = back_step
            if back_step_after is not None and _back(i - 1) and not _back(i):
                step_frac = back_step_after
            base = line_step * step_frac
        else:
            base = line_step
        steps.append(base)

    if anchor == "first":
        ys = [h / 2.0]
    elif not any_back_in_clip:
        ys = [h / 2.0 - (n - 1) / 2.0 * line_step]
    elif not _back(0) and n > 1:
        ys = [h / 2.0 - (n - 1) * 60.0 * step_k]
    else:
        ys = [h / 2.0 - sum(steps) / 2.0]
    for stp in steps:
        ys.append(ys[-1] + stp)
    return [round(y, 2) for y in ys]


# ---- Интро гаснет к субтитру, если стоит на его месте -------------------
# Разбор reelsi_batch.aep владельца: 69 из 76 правленых руками групп интро гаснут РОВНО
# в момент появления следующего субтитра (медиана отклонения 1 кадр), а длина затухания
# почти постоянная — 0.15 с. Сам он определил это на глаз и правил руками; здесь то же
# правило считает Python: группа, чей блок по вертикали лежит на полосе субтитров, гаснет
# к появлению следующего субтитра. Блок, уехавший по Y (полосы не касается), живёт как
# раньше — ровно это владелец и делал руками (группы, сдвинутые по Y, не трогал).
#
# Геометрия блока — те же числа, что у превью и шаблона: Y базовых линий (ys) и кегль
# строк в прекомпе, масштаб прекомпа INTRO_SCALE·ds/100, общий масштаб интро G, позиция
# группы (intro_y/intro_y2, iDy, dy) и зум Камеры 1 (пока интро к ней привязано).
# Второй копии формул здесь нет: sizes берёт правило «задний план/большая строка»
# (intro_line_sizes), верх строки — капитель (_cap), низ — выносные (_desc).
# Полоса субтитров — posy и кегль субтитров, у стопки жёлтых плюс её высота.


def intro_line_sizes(lines: list[dict[str, Any]] | None, fsize: float, back_scale: float = 1.0, lk: Sequence[float | None] | None = None) -> list[float]:
    """Кегль каждой строки интро, px: fsize у обычной строки,
    fsize·back_scale у строки заднего плана, fsize·lk у большой строки.

    Ровно это правило ставят шаблон (introBackScale/introBigScale) и превью
    (fontSize × bsc/lk) — своё здесь не заводится, иначе геометрия блока разошлась бы
    с тем, что видно на экране. Пустой/None список — пустой результат.
    """
    out = []
    for k, ln in enumerate(lines or []):
        k_lk = lk[k] if (lk and k < len(lk)) else None
        if k_lk is not None:
            out.append(float(fsize) * float(k_lk))
        elif (ln or {}).get("back"):
            out.append(float(fsize) * float(back_scale))
        else:
            out.append(float(fsize))
    return out


def _desc(ps: str | None, size: float) -> float:
    """Глубина выносных под базовой линией, px: низ «y» из контуров глифа.
    Файла шрифта или глифа нет — 0.24 кегля (та же запасная ветка, что у капители: блок
    обязан считаться и без файла шрифта — иначе группа молча перестала бы гаснуть)."""
    ext = _fonts.ink_extent(ps, "y", size)
    if ext is None:
        return 0.24 * size
    return float(ext[1])


def intro_block_span(ys: Sequence[float | None], sizes: Sequence[float], h: float, ds: float = 100.0, g: float = 100.0, y: float = 0.0, dy: float = 0.0,
                     zoom: float = 100.0, intro_cam: bool = True, fonts: Sequence[str | None] | None = None) -> tuple[float, float]:
    """(top, bottom) — вертикальный габарит блока интро в кадре, px от верха кадра.
    Верх блока — по капители самой верхней строки, низ — по выносным
    нижней (вертикаль типографская, как в intro_big_layout).

    ys — Y базовых линий строк в координатах прекомпа высотой h; sizes — их кегли
    (intro_line_sizes); fonts — PostScript-имена строк (None/короче — запасная ветка).
    ds — масштаб группы (поле ds плана), g — общий масштаб интро (intro_scale),
    y — позиция блока от центра кадра (plan.intro[].y, уже с G·(−INTRO_BASE_Y+iDy)),
    dy — смещение группы (умножается на G, как в шаблоне и превью), zoom — зум Камеры 1
    в процентах на нужный момент; intro_cam=False (интро откреплено) — зум
    не применяется ни к размеру, ни к позиции. Пустые ys — (0, 0)."""
    if not ys:
        return 0.0, 0.0
    _sizes = list(sizes or [])
    _fonts = list(fonts or [])
    top_pc = bot_pc = None
    for i, yv in enumerate(ys):
        if yv is None:
            continue
        size = float(_sizes[i]) if i < len(_sizes) else 0.0
        ps = _fonts[i] if i < len(_fonts) else None
        t_i = float(yv) - (_cap(ps, size) if size else 0.0)
        b_i = float(yv) + (_desc(ps, size) if size else 0.0)
        top_pc = t_i if top_pc is None else min(top_pc, t_i)
        bot_pc = b_i if bot_pc is None else max(bot_pc, b_i)
    if top_pc is None:
        return 0.0, 0.0
    zk = (float(zoom) / 100.0) if intro_cam else 1.0
    center = h / 2.0 + zk * (float(y) + float(g) / 100.0 * float(dy))
    # Масштаб прекомпа: 96.8·ds/100 (то же iSc, что в шаблоне и в ipvIntroPos), × G
    # (масштаб нула «интро») и × зум Камеры 1, пока интро на ней.
    k = (INTRO_SCALE / 100.0) * (float(ds) / 100.0) * (float(g) / 100.0) * zk
    return (center + (top_pc - h / 2.0) * k, center + (cast(float, bot_pc) - h / 2.0) * k)


def sub_span(posy: float, size: float, font: str | None = None, row: int = 0, step: float = 0.0) -> tuple[float, float]:
    """(top, bottom) — вертикальная полоса субтитров в кадре, px от верха кадра.
    posy — Y базовой линии строки (plan.posy), size — кегль субтитров, row/step — ряд
    стопки жёлтых (её слова идут ниже на шаг hl_step, как в preview ipvSubs); верх — по
    капители, низ — по выносным. size=0 — (posy, posy)."""
    if not size:
        return float(posy), float(posy)
    top = float(posy) - _cap(font, size)
    bot = float(posy) + float(row or 0) * float(step or 0.0) + _desc(font, size)
    return top, bot


def spans_hit(a: tuple[float, float], b: tuple[float, float]) -> bool:
    """Пересекаются ли две вертикальные полосы. Касание краями — не
    пересечение: блок, чей низ ровно на верхе полосы субтитров, на неё не заходит."""
    return a[0] < b[1] and b[0] < a[1]


def intro_hits_subs(ys: Sequence[float | None], sizes: Sequence[float], posy: float, sub_size: float, h: float = 1920.0, ds: float = 100.0, g: float = 100.0,
                    y: float = 0.0, dy: float = 0.0, zoom: float = 100.0, intro_cam: bool = True, fonts: Sequence[str | None] | None = None,
                    sub_font: str | None = None, sub_row: int = 0, sub_step: float = 0.0) -> bool:
    """Стоит ли блок интро на полосе субтитров, True/False.

    Одна дверь для решения «группа гаснет к появлению следующего субтитра»: сборка
    зовёт её на готовых числах плана (ys/кегли/ds/y/dy) и на полосе субтитров
    (posy/кегль/ряд стопки), превью и .jsx своей копии не держат вовсе."""
    return spans_hit(intro_block_span(ys, sizes, h, ds=ds, g=g, y=y, dy=dy,
                                      zoom=zoom, intro_cam=intro_cam, fonts=fonts),
                     sub_span(posy, sub_size, font=sub_font, row=sub_row, step=sub_step))


def intro_sub_window(in_at: float, te: float, next_sub: float, sub_fade: float, f_in: float = INTRO_F_DUR) -> tuple[float, float, float]:
    """(te, fade, fade_start) — окно группы, гаснущей к появлению субтитра.

    Группа гаснет РОВНО к next_sub: te = next_sub, затухание sub_fade секунд, начало
    затухания next_sub − sub_fade, но не раньше конца фейд-ина группы (in_at + F_DUR) —
    иначе затухание начиналось бы раньше, чем блок успел появиться. Окна не хватает —
    затухание короче (вплоть до нуля: появление субтитра на самом фейд-ине — жёсткий
    срез). Числа те же, что у обычного окна: их читают и план (превью), и шаблон."""
    fstart = max(float(next_sub) - float(sub_fade), float(in_at) + float(f_in))
    return (float(next_sub), max(0.0, float(next_sub) - fstart), fstart)


# Анимации вставок, раньше жили константами в AE_FULL (правка .jsx руками влияла на
# сборку): переехали сюда вместе с расчётом ключей — у анимации один источник.
# Пиксельные из них (INS_BLUR, INS_RISE_DY, INS_C1_LOW/HIGH) — px кадра 1080: под
# кадр ролика их множит `_px_k`, иначе в 4K-кадре блюр и вылет вставки были бы вдвое
# мельче её самой (карточка выросла, а анимация нет).
INS_BLUR = 41.0                     # Box Blur cam2-вставки, px кадра 1080 (полный блюр на входе)
INS_RISE_DY, INS_RISE_S0, INS_RISE_ENTER = 132.0, 0.706, 0.5   # анимация «rise»: подъём px (кадр 1080), доля целевого масштаба на старте, вход сек
INS_C2_PEAK, INS_C2_BASE = 100.0, 44.0  # cam2: пик наезда = осевший scale * PEAK/BASE
INS_C2_Y_FR = 0.172                 # cam2: Y точки покоя в долях H (≈330 при 1920) — доля, не px
INS_C1_UP, INS_C1_DN = 0.68, 0.80   # cam1 («из-за спины»): время подъёма над спиной и спуска, сек
INS_C1_LOW, INS_C1_HIGH = 464.7, 567.0  # cam1: нижняя точка старта и высота вылета, px кадра 1080
# Тень плашки под субтитрами: чёрная, снята из adcut.aep
SUB_BG_SH_OP = 173.4                # Opacity (0..255 в AE, 68%)
SUB_BG_SH_DIR = 181.0               # Direction (градусы)
SUB_BG_SH_DIST = 5.0                # Distance (px)
SUB_BG_SH_SOFT = 44.0               # Softness (px)


def _media_dims(path: str | None) -> tuple[int, int] | None:
    """(w, h) видео КАК ПОКАЗЫВАЕТСЯ (с учётом поворота — как item.width/height в AE)
    или None, если файла нет/размер не прочитался. Тогда вставку не трогаем вовсе —
    то же, что if(!iw||!ih) return в старом JS."""
    if not path or not os.path.isfile(path):
        return None
    try:
        from core import draftrender  # lazy: только для видео-вставок
        w, h, _rot = draftrender._display_dims(path)
        return (w, h) if w and h else None
    except ReelsiError: raise
    except Exception:  # размер видео не прочитан — вставку не трогаем вовсе (как в старом JS, см. docstring)
        return None


def _fit_scale(iw: float, ih: float, fill: bool, comp_w: float, comp_h: float, k: float | None) -> float | None:
    """Масштаб видеовставки, %: fill=True — заполнение экрана (видео всегда так),
    иначе — ужать, если больше кадра. k = ручной масштаб (доля от авто).
    None, если размеров нет (старое if(!iw||!ih) return)."""
    if not iw or not ih:
        return None
    f = (max(comp_w / iw, comp_h / ih) if fill else min(comp_w / iw, comp_h / ih, 1)) * (k or 1)
    return f * 100


def _fill_slack(iw: float, ih: float, comp_w: float, comp_h: float, k: float | None) -> tuple[float, float]:
    """На сколько px заполняющий кадр ролика вылезает за кадр композиции, в каждую сторону.
    16:9 ролик, вписанный по высоте, вылезает по ширине на ~2300 px (есть что панорамировать),
    а по высоте запаса нет вовсе; ужатая вставка (k<1) кадр не заполняет — вылет нулевой.
    -> (slack_x, slack_y); (0,0), если размеров нет.

    Это СПРАВКА (план несёт её полями slackx/slacky), а НЕ граница позиции: x/y
    видеовставки двигают свободно при любом масштабе — уехав за край
    ролика, вставка открывает кадр камеры, как и в AE. Раньше этим запасом сдвиг
    зажимали, и вертикальное 9:16 (вылета нет ни по одной оси) не двигалось совсем."""
    if not iw or not ih:
        return 0.0, 0.0
    f = max(comp_w / iw, comp_h / ih) * (k or 1)
    return max(0.0, (iw * f - comp_w) / 2), max(0.0, (ih * f - comp_h) / 2)


def _ins_enter_exit(t0: float, t1: float, noexit: bool, fps: float, enter: float = INS_ENTER, exit_: float = INS_EXIT) -> tuple[float, float]:
    """Окна входа/выхода cam2-вставки, сек. Окно короче анимации входа (ИИ округляет
    тайминги до 0.1с, _clip_end умеет подрезать фото под кат) — ключи выходили ИЗ
    ПОРЯДКА: ужимаем вход под факт. -> (en, ex); короче кадра — (0, win), показ без
    анимации (guard win<1/FPS остаётся в JS, он знает win)."""
    win = max(0.0, t1 - t0)
    if win < 1 / float(fps):
        return 0.0, win
    en = min(enter, win if noexit else win * 0.45)
    ex = min(exit_, max(0.0, win - en))
    return en, ex


def _anim_keys(t0: float, t1: float, va: float, vb: float, noexit: bool, en: float, ex: float, fps: float) -> list[list[Any]]:
    """Ключи анимации «вход va->vb, держим vb, выход vb->va» (то, что ставил JS-функцией
    fourKeys). Guard win<1/FPS и ветка noexit жили в ExtendScript — перенесены сюда
    (остаток): превью читает эти же ключи из плана сцены и не повторяет расчёт.
    Окно короче кадра — один ключ (показать vb без анимации); noexit — конец жёсткий.
    Числа округлены как в JSX (_r), чтобы превью и .jsx были биективны."""
    win = max(0.0, t1 - t0)
    if win < 1 / float(fps):
        return [[_r(t0), _r(vb)]]
    keys = [[_r(t0), _r(va)], [_r(t0 + en), _r(vb)]]
    if noexit:
        keys.append([_r(t1), _r(vb)])
    else:
        keys.append([_r(max(t0 + en, t1 - ex)), _r(vb)])
        keys.append([_r(t1), _r(va)])
    return keys


def _blur_keys(t0: float, t1: float, noexit: bool, px_k: float = 1.0) -> list[list[Any]]:
    """Ключи Box Blur cam2-вставки: резкость входит за INS_ENTER, уходит за INS_EXIT.
    БЕЗ guard'а — в старом JS его здесь не было: на окне короче кадра ключи встают за
    концом слоя и не показываются, это безопасно. Повторяем старое поведение буквально.
    px_k — множитель пиксельных констант кадра (`_px_k`): радиус задан для кадра 1080."""
    blur = INS_BLUR * px_k
    keys = [[_r(t0), blur], [_r(t0 + INS_ENTER), 0.0]]
    if noexit:
        keys.append([_r(t1), 0.0])
    else:
        keys.append([_r(max(t0 + INS_ENTER, t1 - INS_EXIT)), 0.0])
        keys.append([_r(t1), blur])
    return keys


def _cam1_pos_keys(t0: float, t1: float, noexit: bool, ix: float, iy: float, fps: float, cx: float = 0.0, cy: float = 0.0, px_k: float = 1.0) -> list[list[Any]]:
    """Ключи Position cam1-вставки «вылет из-за спины» (то, что ставил JS по INS_C1_*).
    Подъём/спуск сжимаются под окно: потолок 30 кадров на фазу — на коротком окне вылет
    не успевал начаться и фото не появлялось в кадре. cx/cy — точка покоя родительского
    нула (0,0 у «вставки кам1»/«вставки кам1 на кам2» — они существуют всегда).
    Старт dn БЕЗ ix/iy, как в JS: сдвиг точки покоя применяется уже над нулём.
    px_k — множитель пиксельных констант кадра (`_px_k`): вылет и нижняя точка заданы
    для кадра 1080."""
    iwin = max(0.0, t1 - t0)
    c1up = min(INS_C1_UP, 30.0 / float(fps), iwin if noexit else iwin * 0.45)
    c1dn = min(INS_C1_DN, 30.0 / float(fps), max(0.0, iwin - c1up))
    hs = t0 + c1up
    he = t1 if noexit else max(hs, t1 - c1dn)
    up = [_r(cx + ix), _r(cy - INS_C1_HIGH * px_k + iy)]
    dn = [_r(cx), _r(cy + INS_C1_LOW * px_k)]
    keys = [[_r(t0), dn], [_r(hs), up]]
    if noexit:
        keys.append([_r(t1), up])
    else:
        keys.append([_r(he), up])
        keys.append([_r(t1), dn])
    return keys


